#!/usr/bin/env node
/*
 * tools/native-assets.js — a natively compiled toy's art, as ROM data.
 *
 *   node tools/native-assets.js TOYDIR FIRST_BANK OUT.c
 *
 * The studio's importer (renderer/pce-toyhost.js, readAssets) turns a toy's
 * tiles.json, palettes.json and sprites.json into the hardware's own words: the
 * VRAM image, the 512 colour words, the sprite list (which sits in VRAM at $7F00)
 * and the scroll and control registers.  The browser puts them there before the
 * toy's first statement; a native ROM has to do the same at boot.  This tool
 * writes that picture as C: the colour words, then the VRAM words of every run of
 * non-zero data (gaps shorter than 8 words are kept inside a run), as one byte
 * stream cut into 8 KiB pieces, each in its own ROM bank `.rom_bankN` (N from
 * FIRST_BANK up), plus a small run table, the bank number and the registers in the
 * fixed page.  tools/toyc/toy_assets.c replays it in toy_assets_boot().
 *
 * Prints "BANKS a b ..." (the banks used), or "NONE" and writes nothing when the
 * toy has no art.  Nothing here reads the toy's main.lua.
 */
"use strict";
const fs = require("fs");
const path = require("path");
const toyhost = require("../renderer/pce-toyhost.js");

const dir = process.argv[2], first = +process.argv[3], out = process.argv[4];
if (!dir || !first || !out) { console.error("usage: node tools/native-assets.js TOYDIR FIRST_BANK OUT.c"); process.exit(2); }

const files = toyhost.importer.FILES.filter((n) => fs.existsSync(path.join(dir, n)))
  .map((n) => ({ name: n, source: fs.readFileSync(path.join(dir, n), "utf8") }));
const w = files.length ? toyhost.importer.read(files) : null;
if (!w) { console.log("NONE"); process.exit(0); }

const words = new Uint16Array(w.vram.buffer, w.vram.byteOffset, w.vram.length / 2);
const cram = new Uint16Array(w.cram.buffer, w.cram.byteOffset, w.cram.length / 2);
const GAP = 8;
const runs = [];
for (let i = 0; i < words.length;) {
  if (!words[i]) { i++; continue; }
  let end = i + 1, zeros = 0;
  for (let j = i + 1; j < words.length; j++) {
    if (words[j]) { end = j + 1; zeros = 0; } else if (++zeros >= GAP) break;
  }
  runs.push({ vram: i, count: end - i });
  i = end;
}

const blob = [];
for (const c of cram) blob.push(c & 0xFF, c >> 8);
const table = [];
for (const r of runs) {
  table.push({ vram: r.vram, off: blob.length, count: r.count });
  for (let k = 0; k < r.count; k++) { const v = words[r.vram + k]; blob.push(v & 0xFF, v >> 8); }
}
if (table.some((t) => t.off > 0xFFFF)) { console.error("the art is over 64 KiB of stream"); process.exit(1); }

const nbanks = Math.ceil(blob.length / 8192);
const lines = [];
lines.push("/* generated by tools/native-assets.js from " + path.basename(path.resolve(dir)) + ": do not edit */");
lines.push("#include <stdint.h>");
lines.push("#include \"toy_assets.h\"");
lines.push("");
for (let b = 0; b < nbanks; b++) {
  const part = blob.slice(b * 8192, (b + 1) * 8192);
  lines.push("const uint8_t toy_art_blob_" + b + "[" + part.length + "] __attribute__((section(\".rom_bank" + (first + b) + "\"), used, retain)) = {");
  for (let i = 0; i < part.length; i += 24) lines.push("  " + part.slice(i, i + 24).join(",") + ",");
  lines.push("};");
}
lines.push("const uint8_t toy_art_first_bank = " + first + ";");
lines.push("const uint16_t toy_art_nruns = " + table.length + ";");
/* .rodata, not the zero-page copy the compiler would pick for a small const table: that copy was all zeros at run time (measured) */
lines.push("const struct toy_art_run toy_art_runs[" + Math.max(1, table.length) + "] __attribute__((section(\".rodata.toy_art_runs\"), used, retain)) = {");
table.forEach((t) => lines.push("  { " + t.vram + ", " + t.off + ", " + t.count + " },"));
if (!table.length) lines.push("  { 0, 0, 0 },");
lines.push("};");
const r = w.regs;
lines.push("const uint16_t toy_art_bxr = " + r.BXR + ", toy_art_byr = " + r.BYR + ", toy_art_mwr = " + r.MWR + ", toy_art_cr = " + r.CR + ";");
fs.writeFileSync(out, lines.join("\n") + "\n");
const banks = []; for (let b = 0; b < nbanks; b++) banks.push(first + b);
console.error("art: " + table.length + " runs, " + blob.length + " bytes (" + runs.reduce((a, x) => a + x.count, 0) + " VRAM words, 512 colours) in " + nbanks + " bank(s)");
console.log("BANKS " + banks.join(" "));
