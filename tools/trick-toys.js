#!/usr/bin/env node
/*
 * tools/trick-toys.js — write or check renderer/trick-toys.js, the five toys
 * the Hardware tricks page (renderer/tricks.html, card #243) opens in the
 * studio.
 *
 * These are teaching toys, not Browse entries: #151 took the #29 effects out
 * of the gallery, so they are carried in a module of their own and reached by
 * `studio.html?demo=trick-…`.  The sources are the toys' own files, read here
 * and never copied by hand; the titles and blurbs live in this file.
 *
 *   node tools/trick-toys.js             the module on stdout
 *   node tools/trick-toys.js --write     write renderer/trick-toys.js
 *   node tools/trick-toys.js --check     exit 1 if the committed file is not
 *                                        exactly what this tool writes
 *
 * tests/check-tricks.js runs --check, loads the module in the studio page,
 * and runs every toy through both runtimes and the validator.
 */
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const TOYS = path.join(ROOT, "toys");
const OUT = path.join(ROOT, "renderer", "trick-toys.js");

/* In the order the page tells the tricks.  `file` is relative to toys/. */
const TOYS_META = [
  {
    id: "trick-raster",
    file: "tricks/raster-bar.lua",
    title: "Raster bar and per-line palette",
    blurb: "One flat tile becomes a sky: a palette word is rewritten for every " +
      "display line, and a bright bar is the same write choosing another colour."
  },
  {
    id: "trick-palette",
    file: "palette-cycle.lua",
    title: "Palette cycling",
    blurb: "Water and fire by rotating palette entries: the tiles and the map " +
      "never change after init(), only the colours they name."
  },
  {
    id: "trick-parallax",
    file: "parallax.lua",
    title: "Parallax by line scroll",
    blurb: "Four bands of one background scroll at four speeds, because the " +
      "line interrupt writes BXR once per band."
  },
  {
    id: "trick-fade",
    file: "tricks/fade.lua",
    title: "Fades: 7 steps and 14 half-steps",
    blurb: "A 7-step fade to black above a 14-half-step red-to-blue crossfade, " +
      "with the intermediate palette words measured."
  },
  {
    id: "trick-sprites",
    file: "tricks/sprite-limit.lua",
    title: "Sprite limits per line",
    blurb: "16 16-px sprites on one line and 8 32-px CGX sprites on another: " +
      "both are exactly the 16-strip budget, and the background costs none of it."
  }
];

function readFile(file, id) {
  if (!fs.existsSync(file)) {
    throw new Error("no " + path.relative(ROOT, file) + " for the tricks " +
                    "page's " + id + " (tools/trick-toys.js)");
  }
  const text = fs.readFileSync(file, "utf8");
  if (!text) throw new Error(path.relative(ROOT, file) + " is empty");
  return text;
}

function data() {
  const seen = new Set();
  const toys = TOYS_META.map((meta) => {
    if (seen.has(meta.id)) throw new Error("duplicate trick id " + meta.id);
    seen.add(meta.id);
    const file = path.join(TOYS, meta.file);
    return {
      id: meta.id,
      file: meta.file,
      name: path.basename(meta.file),
      title: meta.title,
      blurb: meta.blurb,
      source: readFile(file, meta.id)
    };
  });
  return { version: 1, toys: toys };
}

function render() {
  return "/*\n" +
    " * trick-toys.js — the five Hardware tricks toys (card #243), as\n" +
    " * renderer/tricks.html and the studio read them.  The studio opens one\n" +
    " * with `studio.html?demo=trick-…`; they are NOT Browse entries (the\n" +
    " * gallery is tools/gallery.js's).\n" +
    " *\n" +
    " * GENERATED by tools/trick-toys.js from toys/; do not edit by hand.  The\n" +
    " * titles and blurbs are that tool's TOYS_META, the sources are the toys'\n" +
    " * own files, so the page, the studio and tests/check-tricks.js cannot\n" +
    " * drift.  `node tools/trick-toys.js --check` says whether this file still\n" +
    " * matches; `--write` regenerates it.\n" +
    " */\n" +
    "(function (root, factory) {\n" +
    "  if (typeof module === \"object\" && module.exports) {\n" +
    "    module.exports = factory();\n" +
    "  } else {\n" +
    "    root.PCEStudio = root.PCEStudio || {};\n" +
    "    root.PCEStudio.trickData = factory();\n" +
    "  }\n" +
    "})(typeof globalThis !== \"undefined\" ? globalThis : this, function () {\n" +
    "  \"use strict\";\n" +
    "  return " + JSON.stringify(data(), null, 2) + ";\n" +
    "});\n";
}

function main(argv) {
  const args = argv.slice(2);
  let mode = "stdout";
  for (const a of args) {
    if (a === "--write") mode = "write";
    else if (a === "--check") mode = "check";
    else if (a === "--help" || a === "-h") {
      process.stdout.write("usage: node tools/trick-toys.js [--write | --check]\n");
      return 0;
    } else {
      process.stderr.write("unknown argument: " + a + "\n");
      return 2;
    }
  }
  let text;
  try {
    text = render();
  } catch (e) {
    process.stderr.write("trick-toys: " + e.message + "\n");
    return 2;
  }
  if (mode === "write") {
    fs.writeFileSync(OUT, text);
    process.stdout.write("wrote " + path.relative(ROOT, OUT) + "\n");
    return 0;
  }
  if (mode === "check") {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== text) {
      process.stderr.write("renderer/trick-toys.js is out of date; run " +
                           "node tools/trick-toys.js --write\n");
      return 1;
    }
    process.stdout.write("renderer/trick-toys.js is current\n");
    return 0;
  }
  process.stdout.write(text);
  return 0;
}

if (require.main === module) process.exit(main(process.argv));

module.exports = { data, render, TOYS_META };
