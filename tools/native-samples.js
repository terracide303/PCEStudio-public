#!/usr/bin/env node
/*
 * tools/native-samples.js — a natively compiled toy's samples, as one ROM data bank.
 *
 *   node tools/native-samples.js TOYDIR BANK OUT.c
 *
 * Reads TOYDIR/samples.json (renderer/pce-sample.js: written by tools/wav2sample.js), builds the 8 KiB
 * sample bank (a count, an 8-byte entry per sample, then the steps) and writes it as C in ROM bank
 * `.rom_bankBANK`, plus `toy_smp_bank`, the bank number the sample interrupt maps into page 3.
 * Prints "BANKS BANK", or exits 1 with the code when the budget or the file is refused.
 */
"use strict";
const fs = require("fs");
const path = require("path");
const sample = require("../renderer/pce-sample.js");

const [dir, bankArg, out] = process.argv.slice(2);
const bank = +bankArg;
if (!dir || !bank || !out) { console.error("usage: node tools/native-samples.js TOYDIR BANK OUT.c"); process.exit(2); }
try {
  const text = fs.readFileSync(path.join(dir, "samples.json"), "utf8");
  const list = sample.parse(text);
  const bytes = sample.build(list);
  const lines = ["/* generated by tools/native-samples.js from " + path.basename(path.resolve(dir)) + ": do not edit */",
    "#include <stdint.h>",
    "const uint8_t toy_smp_blob[8192] __attribute__((section(\".rom_bank" + bank + "\"), used, retain)) = {"];
  for (let i = 0; i < bytes.length; i += 32) lines.push("  " + Array.from(bytes.slice(i, i + 32)).join(",") + ",");
  lines.push("};", "const uint8_t toy_smp_bank = " + bank + ";");
  fs.writeFileSync(out, lines.join("\n") + "\n");
  const c = sample.check(list);
  console.error("samples: " + list.length + ", " + c.bytes + " of " + c.max + " bytes in bank " + bank);
  console.log("BANKS " + bank);
} catch (e) {
  console.error("native-samples failed: " + (e.code || "error") + ": " + e.message);
  process.exit(1);
}
