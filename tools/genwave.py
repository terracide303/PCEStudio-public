#!/usr/bin/env python3
"""genwave.py — the PCEAS reference path for the #35 wave editor.

Reads a sound written by tools/wavesounds.js (renderer/pce-wave.js's document,
tools/gen/waveN.sound.json) and produces, for each:

  tools/gen/waveN.asm          a straight-line HuC6280 program that writes the
                               patch's PSG registers ($0800-$0809) and then
                               idle-loops (`bra *`) — no VDC/VCE/timer/IRQ, so
                               the recorded WAV is a pure PSG witness (the shape
                               of #34's tools/genpsg.py ROMs)
  tools/gen/waveN.trace.json   every register write at its (frame, in-frame
                               CPU cycle) under Mednafen pce_fast's HuC6280
                               timeslice schedule, plus the per-frame
                               durations — from genpsg.py's simulate(), the
                               simulator #34 proved sample-exact

PCEAS assembles the asm (`pceas -raw -o tools/gen/waveN.pce
tools/gen/waveN.asm`); tests/check-wave.js compares that 8 KiB image with
renderer/pce-wave.js's buildRom() from the same sound, byte for byte, and the
trace here with pce-wave.js's trace() — then compares the model's PCM against
Mednafen's recording of the ROM (tools/capture-wave.sh).

The instruction order is pce-wave.js's `instructions()`: both passes at
R4 = 0 (write frequency and wave while the channel is off), the global volume,
then the enabling pass, then the LFO (R9 bit 7 restarts the carrier).  Their
agreement is checked, not assumed.

This file does not define a sound: tools/wavesounds.js is the one definition,
so a change to the editor's document cannot silently leave the reference
behind.
"""

import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, "gen")

CLOCK = 7159090          # PCE_MASTER_CLOCK / 3 (pce_fast)
SAMPLE_RATE = 44100


def load_genpsg():
    """#34's simulator, loaded by path (python3 -I drops the script dir)."""
    path = os.path.join(HERE, "genpsg.py")
    spec = importlib.util.spec_from_file_location("genpsg", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def check(cond, message):
    if not cond:
        sys.exit(f"genwave.py: {message}")


def writes_for(sound):
    """The register writes, in pce-wave.js's order: [(reg, value), ...]."""
    out = []
    chans = sound["channels"]
    check(len(chans) == 6, "a sound has six channels")
    for c, ch in enumerate(chans):
        check(0 <= ch["freq"] <= 0xFFF, f"channel {c}: frequency 0..4095")
        check(0 <= ch["al"] <= 0x1F, f"channel {c}: AL 0..31")
        check(0 <= ch["balance"] <= 0xFF, f"channel {c}: balance 0..255")
        check(len(ch["wave"]) == 32, f"channel {c}: 32 wave steps")
        for i, v in enumerate(ch["wave"]):
            check(0 <= v <= 31, f"channel {c} step {i}: wave 0..31")
        out.append((0, c))                        # select
        out.append((4, 0x00))                     # off, waveform mode
        out.append((2, ch["freq"] & 0xFF))        # frequency LSB
        out.append((3, (ch["freq"] >> 8) & 0x0F))  # frequency MSB
        noise = ch.get("noise")
        if c >= 4 and noise and noise["on"]:
            check(0 <= noise["nf"] <= 0x1F, f"channel {c}: NF 0..31")
            out.append((7, 0x80 | (noise["nf"] & 0x1F)))
        if c >= 4 and noise and not noise["on"]:
            out.append((7, noise["nf"] & 0x1F))
        for v in ch["wave"]:
            out.append((6, v))
        out.append((5, ch["balance"]))

    mv = sound["mainVolume"]
    check(0 <= mv <= 0xFF, "main volume 0..255")
    out.append((1, mv))

    lfo = sound.get("lfo") or {"freq": 0, "ctl": 0}
    on = bool(lfo.get("ctl"))
    for c, ch in enumerate(chans):
        if on and c == 1:
            control = 0x80                        # the silent LFO carrier
        elif ch["on"]:
            control = 0x80 | (ch["al"] & 0x1F)
        else:
            control = 0x00
        out.append((0, c))
        out.append((4, control))
    if on:
        check(0 <= lfo["freq"] <= 0xFF, "LFO frequency 0..255")
        check(1 <= lfo["ctl"] <= 3, "LFCTL 1..3")
        out.append((8, lfo["freq"]))
        # the trigger is a strobe: bit 7 restarts the carrier and (pce_fast's
        # guess, docs/PSG.md) freezes it while set, so clear it after
        out.append((9, 0x80 | lfo["ctl"]))
        out.append((9, lfo["ctl"]))
    return out


def emit_asm(name, what, writes):
    """The same instruction stream pce-wave.js encodes: LDA #imm / STA abs
    pairs (7 cycles), then `bra *` (4 cycles), then the vectors."""
    lines = [
        ";;",
        f";; {name}.asm — generated by tools/genwave.py, do not edit.",
        f";; {what}",
        ";; Build: pceas -raw -o tools/gen/waveN.pce tools/gen/waveN.asm",
        ";;",
        "        .code",
        "        .bank 0",
        "        .org $fff6",
        "        .dw irq2",
        "        .dw irq1",
        "        .dw timer",
        "        .dw nmi",
        "        .dw reset",
        "",
        "        .code",
        "        .bank 0",
        "        .org $e000",
        "",
        "reset:",
        "        sei",
        "        csh",
        "        cld",
    ]
    for reg, value in writes:
        lines.append(f"        lda #${value:02x}")
        lines.append(f"        sta ${0x0800 + reg:04x}")
    lines += [
        "loop:",
        "        bra loop",
        "",
        "irq2:",
        "irq1:",
        "timer:",
        "nmi:",
        "        rti",
        "",
    ]
    with open(os.path.join(GEN, f"{name}.asm"), "w") as f:
        f.write("\n".join(lines))


def main():
    genpsg = load_genpsg()
    os.makedirs(GEN, exist_ok=True)
    names = sys.argv[1:] or sorted(
        f[:-len(".sound.json")] for f in os.listdir(GEN)
        if f.endswith(".sound.json"))
    check(names, "no tools/gen/*.sound.json — run node tools/wavesounds.js")
    for name in names:
        path = os.path.join(GEN, f"{name}.sound.json")
        with open(path) as f:
            doc = json.load(f)
        writes = writes_for(doc["sound"])
        # genpsg.simulate() appends the idle `bra *` itself
        ops = [(cyc, w) for (cyc, w) in
               [(2, None), (3, None), (2, None)]
               + [(7, w) for w in writes]]
        events, T = genpsg.simulate(ops)
        k_last = events[-1][0] if events else 0
        extra = T[1:k_last + 1]
        steady = T[k_last + 1:]
        pattern = None
        for p in range(1, 5):
            if all(steady[i] == steady[i % p] for i in range(len(steady))):
                pattern = steady[:p]
                break
        check(pattern is not None, f"{name}: the idle tail is not periodic")
        trace = {
            "name": name,
            "what": doc["what"],
            "clock": CLOCK,
            "sample_rate": SAMPLE_RATE,
            "events": [{"f": f, "t": t, "reg": reg, "value": value}
                       for (f, t, reg, value) in events],
            "frames": {"t0": T[0], "extra": extra, "pattern": pattern},
        }
        with open(os.path.join(GEN, f"{name}.trace.json"), "w") as f:
            json.dump(trace, f, indent=1)
            f.write("\n")
        emit_asm(name, doc["what"], writes)
        print(f"{name}: {len(events)} writes, {len(events)} events, "
              f"frame0 {T[0]}, extra {extra}, pattern {pattern}")


if __name__ == "__main__":
    main()
