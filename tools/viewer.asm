;;
;; PCEStudio — viewer.asm (cards #8, #14)
;;
;; The viewer ROM: loads the 512-entry colour table into the VCE, tiles and
;; the BAT (and for the sprite scenes the SG patterns) into VRAM, the SAT
;; into VRAM $7f00 where the VDC's SATB DMA picks it up every frame, sets
;; the VDC to 256x224 and shows the picture.  All picture data is read from
;; fixed places in the ROM; the layout is documented in ../docs/ROM_LAYOUT.md
;; (bank 1: config + 512-entry palettes + the SAT, banks 2-3: BAT,
;; banks 4+: tiles, concatenated in descriptor order).  Bank 0 is this code
;; and never changes — #9 glues picture data into the fixed places, so the
;; browser's .pce is this bank plus data banks.
;;
;; The data banks are generated by tools/genviewer.py from the dumps in
;; tests/dumps/ (see the Makefile); this file alone assembles to the 8 KiB
;; code bank.
;;
;; Adapted from HuDK (BlockoS/HuDK, MIT).  The parts taken from it:
;;   - the reset path (include/irq_reset.s _reset: sei/csh/cld, stack,
;;     tam0/tam1)
;;   - the VDC 256x224 register values (include/vdc.s vdc_init_table)
;;   - the VCE dot-clock value and palette write sequence (include/vce.s
;;     vce_init, vce_load_palette — via the VCE ports, own loop)
;;   - the ROM->VRAM copy pattern with bank remapping (include/vdc.s
;;     vdc_load_data + include/map.s map_data/remap_data: read through an
;;     8 KiB MPR window, re-map the window when the pointer crosses it)
;; The loader, the fixed data layout and the BAT word-count table are ours.
;; The licence notice and adaptation record are at the bottom.
;;
;; Build: see ../docs/BUILD.md.
;;

        .code
        .bank 0
        .org $fff6
        .dw irq2                   ; $fff6
        .dw irq1                   ; $fff8
        .dw timer                  ; $fffa
        .dw nmi                    ; $fffc
        .dw reset                  ; $fffe

        .code
        .bank 0
        .org $e000

; Zero-page scratch.  Every access needs the < prefix: pceas emits a bare
; $xx as a 16-bit absolute address, which through MPR0=$ff aliases the I/O
; page instead of the zp RAM.
src      = $10          ; ROM window pointer (src+1 = high byte)
src_bank = $12          ; ROM bank mapped into $4000-$5fff (MPR2)
wcnt     = $13          ; word count (wcnt+1 = high byte)
rgns     = $15          ; tile region counter
cfg      = $16          ; config descriptor pointer (cfg+1 = high byte)

reset:
        sei                        ; no interrupts
        csh                        ; fast CPU clock
        cld
        ldx #$ff
        txs
        lda #$ff
        tam0                       ; I/O at $0000-$1fff
        lda #$f8
        tam1                       ; work RAM at $2000-$3fff

        ; VCE: 256 px dot clock, edge blur on (HuDK vce_init value)
        lda #$04
        sta $0400

        ; config + palettes live in bank 1, read through MPR2 ($4000-$5fff)
        lda #$01
        tam2

        ; Copy the 64-byte config block to RAM $2200 (just above the stack,
        ; which only ever holds the two-byte jsr return addresses at $21ff).
        ; The region loop must read its descriptors while MPR2 maps the tile
        ; banks, so the config cannot stay in bank 1: read it once into RAM
        ; and be done with it.
        clx
cfgcopy:
        lda $4000, X
        sta $2200, X
        inx
        cpx #$40                   ; 64 bytes
        bne cfgcopy

        ; ---- palettes: entries 0-511 (16 BG + 16 sprite palettes) from
        ; ROM $4040 (1024 bytes, bank 1).  Exactly 512 writes: the CTA is 9
        ; bits, so entry 511's write wraps it to 0 and another write would
        ; wipe palettes 0-15 again.
        stz $0402                  ; colour table index = 0 (autoincrements
        stz $0403                  ; after every $0405 write)
        lda #$40
        sta <src
        lda #$40
        sta <src+1
        ldx #$04                   ; 4 pages x 256 bytes = 1024 bytes = 512 words
palpage:
        cly
palentry:
        lda [src], Y
        sta $0404
        iny
        lda [src], Y
        sta $0405
        iny
        bne palentry
        inc <src+1                 ; next 256-byte page
        dex
        bne palpage

        ; ---- VDC registers (HuDK vdc_init_table values; BXR/BYR/MWR/CR come
        ; from the config block, copied to RAM at $2200)
        st0 #$05
        st1 #$00
        st2 #$00                   ; CR: everything off until the data is in
        st0 #$06
        st1 #$00
        st2 #$00                   ; RCR
        st0 #$07
        lda $2202                  ; BXR lo (config offset $02)
        sta $0002
        lda $2203                  ; BXR hi, 10 bits
        and #$03
        sta $0003
        st0 #$08
        lda $2204                  ; BYR lo
        sta $0002
        lda $2205                  ; BYR hi, 9 bits
        and #$01
        sta $0003
        st0 #$09
        lda $2206                  ; MWR
        sta $0002
        st2 #$00
        st0 #$0a
        st1 #$02
        st2 #$02                   ; HSR: HDS=2, HSW=2
        st0 #$0b
        st1 #$1f
        st2 #$04                   ; HDR: HDW=31, HDE=4
        st0 #$0c
        st1 #$02
        st2 #$0f                   ; VPR
        st0 #$0d
        st1 #$ef
        st2 #$00                   ; VDW: 240 display lines
        st0 #$0e
        st1 #$0c
        st2 #$00                   ; VCR
        st0 #$0f
        st1 #$10
        st2 #$00                   ; DCR: bit 4 (DSR) = VRAM-SATB transfer
                                   ; auto-repeat — the VDC re-DMAs the SAT
                                   ; into the SATB at every VBlank (VDC
                                   ; manual, DCR R0F p. H7-11).  The sprite
                                   ; layer itself is CR bit 6 (below), so
                                   ; this is harmless for sprite-free
                                   ; pictures.
        st0 #$13
        st1 #$00
        st2 #$7f                   ; DVSSR: the SAT sits at VRAM $7f00; the
                                   ; 256-word transfer starts at the next
                                   ; VBlank, triggered by this high-byte
                                   ; write (DVSSR R13 p. H7-12)

        ; ---- BAT: words 0..(width*height-1) of VRAM, from bank 2
        lda $2206                  ; MWR -> word count (HuDK vdc.s bat_width/
        and #$70                   ; bat_height_array order: 32/64/128/128
        lsr A                      ; wide, 32 or 64 rows)
        lsr A
        lsr A
        lsr A
        tax
        lda bat_words_lo, X
        sta <wcnt
        lda bat_words_hi, X
        sta <wcnt+1
        lda #$02
        sta <src_bank
        tam2                       ; map the BAT bank into the window
        stz <src
        lda #$40
        sta <src+1
        st0 #$00
        st1 #$00
        st2 #$00                   ; MAWR = 0
        st0 #$02
        jsr copy_words

        ; ---- tiles: one copy region per config descriptor; the data is the
        ; concatenation of the regions, starting at bank 4 offset 0.  The
        ; descriptors come from the RAM copy of the config ($220a): MPR2 is
        ; mapped to the tile banks for the whole loop, so they cannot be read
        ; from bank 1.
        lda $2208                  ; region count
        sta <rgns
        beq tiles_done
        lda #$04
        sta <src_bank
        tam2                       ; map the first tile bank into the window
        stz <src
        lda #$40
        sta <src+1
        lda #$0a
        sta <cfg
        lda #$22
        sta <cfg+1
region_loop:
        st0 #$00                   ; MAWR = descriptor words 0-1 (VRAM dest)
        cly
        lda [cfg], Y
        sta $0002
        iny
        lda [cfg], Y
        sta $0003
        iny
        lda [cfg], Y               ; word count = descriptor words 2-3
        sta <wcnt
        iny
        lda [cfg], Y
        sta <wcnt+1
        lda <cfg                   ; next descriptor
        clc
        adc #$04
        sta <cfg
        bcc cfg_ok
        inc <cfg+1
cfg_ok:
        st0 #$02
        jsr copy_words
        dec <rgns
        bne region_loop
tiles_done:

        ; ---- SAT: 64 entries x 4 words from bank 1 offset $0440 to VRAM
        ; word $7f00 (DVSSR above).  The CPU cannot write the SATB directly;
        ; the SAT lives in VRAM and the DCR bit-4 DMA carries it into the
        ; SATB at the start of every VBlank (VDC manual 2.4.2 SATB p. H7-20,
        ; DVSSR R13 p. H7-12).  Sprites are still off (CR written below), so
        ; the first displayed frame's SATB already holds this SAT.
        lda #$01
        sta <src_bank
        tam2                       ; map bank 1 back into the window
        lda #$40
        sta <src
        lda #$44
        sta <src+1
        stz <wcnt
        lda #$01
        sta <wcnt+1                ; 256 words
        st0 #$00
        st1 #$00
        st2 #$7f                   ; MAWR = $7f00
        st0 #$02
        jsr copy_words

        ; ---- show it: CR from config (bit 7 = background on, bit 6 =
        ; sprites on)
        st0 #$05
        lda $2207
        sta $0002
        st2 #$00

loop:
        bra loop

;
; copy_words — copy <wcnt words from ROM (bank <src_bank, 16-bit pointer
; <src) to the VDC data port.  The pointer advances across calls: the tile
; regions are concatenated in the ROM, so each copy must continue where the
; last one left off (an earlier page-walk version kept the byte position in
; Y, which each call reset — every region that did not end on a 256-byte
; page was re-read from the page start, the #14 stripes-scene bug).
; Crossing $5fff re-maps MPR2 to the next bank and resets the pointer to
; $4000 (HuDK's remap_data pattern).  Register 2 of the VDC must be
; selected and MAWR set by the caller.  Clobbers A, X, Y.
;
copy_words:
        lda <wcnt
        ora <wcnt+1
        beq copy_done
        cly                        ; Y stays 0: <src> is the whole pointer
copy_word:
        lda <src+1
        cmp #$60
        bne copy_read
        inc <src_bank              ; crossed the 8 KiB window: next bank
        lda <src_bank
        tam2
        lda #$40
        sta <src+1
copy_read:
        lda [src], Y
        sta $0002
        inc <src
        bne copy_second
        inc <src+1
copy_second:
        lda <src+1
        cmp #$60
        bne copy_high
        inc <src_bank
        lda <src_bank
        tam2
        lda #$40
        sta <src+1
copy_high:
        lda [src], Y
        sta $0003
        inc <src
        bne copy_next
        inc <src+1
copy_next:
        lda <wcnt
        bne copy_low
        dec <wcnt+1
copy_low:
        dec <wcnt
        lda <wcnt
        ora <wcnt+1
        bne copy_word
copy_done:
        rts

; BAT word counts by MWR index ((MWR & $70) >> 4): width 32/64/128/128,
; height 32 rows for 0-3, 64 rows for 4-7 (same order as HuDK's
; bat_width_array / bat_height_array).
bat_words_lo:
        .db $00, $00, $00, $00, $00, $00, $00, $00
bat_words_hi:
        .db $04, $08, $10, $10, $08, $10, $20, $20

irq2:
irq1:
timer:
nmi:
        rti

