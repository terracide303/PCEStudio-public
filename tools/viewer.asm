;;
;; PCEStudio — viewer.asm (cards #8, #14, #16)
;;
;; The viewer ROM: loads the 512-entry colour table into the VCE, tiles and
;; the BAT (and for the sprite scenes the SG patterns) into VRAM, the SAT
;; into VRAM $7f00 where the VDC's SATB DMA picks it up every frame, sets
;; the VDC to 256x240 (VDW = $00EF, 240 display lines, H7-10; HDR = $041F,
;; 32 characters = 256 px, H7-9) and shows the picture.  All picture data is
;; read from
;; fixed places in the ROM; the layout is documented in ../docs/ROM_LAYOUT.md
;; (bank 1: config + 512-entry palettes + the SAT + the #16 raster table,
;; banks 2-3: BAT, banks 4+: tiles, concatenated in descriptor order).
;; Bank 0 is this code and never changes — #9 glues picture data into the
;; fixed places, so the browser's .pce is this bank plus data banks.
;;
;; #16: pictures with a raster table (config byte 9 = 1) run it on the
;; console: an irq1 handler driven by the VDC's RCR line interrupt writes
;; each line's BXR/BYR/CR/colour-table values and re-arms RCR for the next
;; entry, one step per VDW line (the table and the handler are described
;; below and in ../docs/ROM_LAYOUT.md / ../docs/RENDERER.md).
;;
;; The data banks are generated by tools/genviewer.py from the dumps in
;; tests/dumps/ (see the Makefile); this file alone assembles to the 8 KiB
;; code bank.
;;
;; Adapted from HuDK (BlockoS/HuDK, MIT).  The parts taken from it:
;;   - the reset path (include/irq_reset.s _reset: sei/csh/cld, stack,
;;     tam0/tam1)
;;   - the VDC 256x240 register values (include/vdc.s vdc_init_table)
;;   - the VCE dot-clock value and palette write sequence (include/vce.s
;;     vce_init, vce_load_palette — via the VCE ports, own loop)
;;   - the ROM->VRAM copy pattern with bank remapping (include/vdc.s
;;     vdc_load_data + include/map.s map_data/remap_data: read through an
;;     8 KiB MPR window, re-map the window when the pointer crosses it)
;; The loader, the fixed data layout and the BAT word-count table are ours.
;; The licence notice and adaptation record are at the bottom.
;;
;; Build: see ../docs/BUILD.md.
;;

        .code
        .bank 0
        .org $fff6
        .dw irq2                   ; $fff6
        .dw irq1                   ; $fff8 — #16: irq1 = the RAM cell $2020,
                                   ; a jmp into the chain handler patched at
                                   ; boot (hardware manual §2.4.2 (1)
                                   ; p. H8-13: IRQ1's vector is $fff8/$fff9)
        .dw timer                  ; $fffa
        .dw nmi                    ; $fffc
        .dw reset                  ; $fffe

        .code
        .bank 0
        .org $e000

; Zero-page scratch.  Every access needs the < prefix: pceas emits a bare
; $xx as a 16-bit absolute address, which through MPR0=$ff aliases the I/O
; page instead of the zp RAM.
src      = $10          ; ROM window pointer (src+1 = high byte)
src_bank = $12          ; ROM bank mapped into $4000-$5fff (MPR2)
wcnt     = $13          ; word count (wcnt+1 = high byte)
rgns     = $15          ; tile region counter
cfg      = $16          ; config descriptor pointer (cfg+1 = high byte)
dst      = $18          ; raster table copy destination (dst+1 = high byte)
nsteps   = $1e          ; raster table: the step count (the wrap compare)
step     = $30          ; raster table: the current step — BaseRAM[0x30],
                        ; the cell the #15 scene ROMs' chains use and
                        ; tools/raster-patch.py reads from the save state
frame    = $31          ; raster table: the frame counter (BaseRAM[0x31],
                        ; the same contract)

; #16: the raster table's parallel per-step arrays in RAM.  Bank 1's copy
; at ROM offset $640 lands at $2800 (16 pages, copied below); the layout
; is fixed for every table — docs/ROM_LAYOUT.md.  Each array is its own
; 256-byte page and holds 240 steps, so the chain's lda array,X never
; crosses a page: every write byte costs 4 cycles.
irq1     = $2020        ; the IRQ1 vector's target: a jmp patched at boot
                        ; to the handler the table's flags select
r_op     = $2804        ; bit 0 BXR, bit 1 BYR, bit 2 CR, bit 3 first
                        ; CRAM word, bit 4 second CRAM word
r_chain_lo = $2900      ; RCR for the next step = 0x40 + its line
r_chain_hi = $29f0
r_bxr_lo = $2ae0        ; the BXR write (10 bits)
r_bxr_hi = $2bd0
r_byr_lo = $2cc0        ; the BYR write (9 bits)
r_byr_hi = $2db0
r_cr     = $2ea0        ; the CR write (8 bits)
r_a1_lo  = $2f90        ; first CRAM word: colour table address (9 bits)
r_a1_hi  = $3080
r_v1_lo  = $3170        ; and value (9 bits)
r_v1_hi  = $3260
r_a2_lo  = $3350        ; second CRAM word
r_a2_hi  = $3440
r_v2_lo  = $3530
r_v2_hi  = $3620

reset:
        sei                        ; no interrupts
        csh                        ; fast CPU clock
        cld
        ldx #$ff
        txs
        lda #$ff
        tam0                       ; I/O at $0000-$1fff
        lda #$f8
        tam1                       ; work RAM at $2000-$3fff

        ; VCE CR ($0400) = $04: D1-D0 = 11, the /4 dot clock (the 256-px
        ; picture, H6-3); D2 is set too, and the sources disagree on what it
        ; is.  The VCE manual documents D1-D0 only (H6-3).  docs/VIDEO_MODES.md
        ; reads bit 2 as a 262/263-line select; Charles MacDonald's measured
        ; hardware notes read it as "blur edges" (pcetech SS6; SS7 says the
        ; frame is 263 lines fixed).  #27 settles which.  The value is
        ; HuDK's vce_init value.
        lda #$04
        sta $0400

        ; config + palettes live in bank 1, read through MPR2 ($4000-$5fff)
        lda #$01
        tam2

        ; Copy the 64-byte config block to RAM $2200 (just above the stack,
        ; which only ever holds the two-byte jsr return addresses at $21ff).
        ; The region loop must read its descriptors while MPR2 maps the tile
        ; banks, so the config cannot stay in bank 1: read it once into RAM
        ; and be done with it.
        clx
cfgcopy:
        lda $4000, X
        sta $2200, X
        inx
        cpx #$40                   ; 64 bytes
        bne cfgcopy

        ; ---- palettes: entries 0-511 (16 BG + 16 sprite palettes) from
        ; ROM $4040 (1024 bytes, bank 1).  Exactly 512 writes: the CTA is 9
        ; bits, so entry 511's write wraps it to 0 and another write would
        ; wipe palettes 0-15 again.
        stz $0402                  ; colour table index = 0 (autoincrements
        stz $0403                  ; after every $0405 write)
        lda #$40
        sta <src
        lda #$40
        sta <src+1
        ldx #$04                   ; 4 pages x 256 bytes = 1024 bytes = 512 words
palpage:
        cly
palentry:
        lda [src], Y
        sta $0404
        iny
        lda [src], Y
        sta $0405
        iny
        bne palentry
        inc <src+1                 ; next 256-byte page
        dex
        bne palpage

        ; ---- VDC registers (HuDK vdc_init_table values; BXR/BYR/MWR/CR come
        ; from the config block, copied to RAM at $2200)
        st0 #$05
        st1 #$00
        st2 #$00                   ; CR: everything off until the data is in
        st0 #$06
        st1 #$00
        st2 #$00                   ; RCR
        st0 #$07
        lda $2202                  ; BXR lo (config offset $02)
        sta $0002
        lda $2203                  ; BXR hi, 10 bits
        and #$03
        sta $0003
        st0 #$08
        lda $2204                  ; BYR lo
        sta $0002
        lda $2205                  ; BYR hi, 9 bits
        and #$01
        sta $0003
        st0 #$09
        lda $2206                  ; MWR
        sta $0002
        st2 #$00
        st0 #$0a
        st1 #$02
        st2 #$02                   ; HSR: HDS=2, HSW=2
        st0 #$0b
        st1 #$1f
        st2 #$04                   ; HDR: HDW=31, HDE=4
        st0 #$0c
        st1 #$02
        st2 #$0f                   ; VPR
        st0 #$0d
        st1 #$ef
        st2 #$00                   ; VDW: 240 display lines
        st0 #$0e
        st1 #$0c
        st2 #$00                   ; VCR
        st0 #$0f
        st1 #$10
        st2 #$00                   ; DCR: bit 4 (DSR) = VRAM-SATB transfer
                                   ; auto-repeat — the VDC re-DMAs the SAT
                                   ; into the SATB at every VBlank (VDC
                                   ; manual, DCR R0F p. H7-11).  The sprite
                                   ; layer itself is CR bit 6 (below), so
                                   ; this is harmless for sprite-free
                                   ; pictures.
        st0 #$13
        st1 #$00
        st2 #$7f                   ; DVSSR: the SAT sits at VRAM $7f00; the
                                   ; 256-word transfer starts at the next
                                   ; VBlank, triggered by this high-byte
                                   ; write (DVSSR R13 p. H7-12)

        ; ---- BAT: words 0..(width*height-1) of VRAM, from bank 2
        lda $2206                  ; MWR -> word count (HuDK vdc.s bat_width/
        and #$70                   ; bat_height_array order: 32/64/128/128
        lsr A                      ; wide, 32 or 64 rows)
        lsr A
        lsr A
        lsr A
        tax
        lda bat_words_lo, X
        sta <wcnt
        lda bat_words_hi, X
        sta <wcnt+1
        lda #$02
        sta <src_bank
        tam2                       ; map the BAT bank into the window
        stz <src
        lda #$40
        sta <src+1
        st0 #$00
        st1 #$00
        st2 #$00                   ; MAWR = 0
        st0 #$02
        jsr copy_words

        ; ---- tiles: one copy region per config descriptor; the data is the
        ; concatenation of the regions, starting at bank 4 offset 0.  The
        ; descriptors come from the RAM copy of the config ($220a): MPR2 is
        ; mapped to the tile banks for the whole loop, so they cannot be read
        ; from bank 1.
        lda $2208                  ; region count
        sta <rgns
        beq tiles_done
        lda #$04
        sta <src_bank
        tam2                       ; map the first tile bank into the window
        stz <src
        lda #$40
        sta <src+1
        lda #$0a
        sta <cfg
        lda #$22
        sta <cfg+1
region_loop:
        st0 #$00                   ; MAWR = descriptor words 0-1 (VRAM dest)
        cly
        lda [cfg], Y
        sta $0002
        iny
        lda [cfg], Y
        sta $0003
        iny
        lda [cfg], Y               ; word count = descriptor words 2-3
        sta <wcnt
        iny
        lda [cfg], Y
        sta <wcnt+1
        lda <cfg                   ; next descriptor
        clc
        adc #$04
        sta <cfg
        bcc cfg_ok
        inc <cfg+1
cfg_ok:
        st0 #$02
        jsr copy_words
        dec <rgns
        bne region_loop
tiles_done:

        ; ---- SAT: 64 entries x 4 words from bank 1 offset $0440 to VRAM
        ; word $7f00 (DVSSR above).  The CPU cannot write the SATB directly;
        ; the SAT lives in VRAM and the DCR bit-4 DMA carries it into the
        ; SATB at the start of every VBlank (VDC manual 2.4.2 SATB p. H7-20,
        ; DVSSR R13 p. H7-12).  Sprites are still off (CR written below), so
        ; the first displayed frame's SATB already holds this SAT.
        lda #$01
        sta <src_bank
        tam2                       ; map bank 1 back into the window
        lda #$40
        sta <src
        lda #$44
        sta <src+1
        stz <wcnt
        lda #$01
        sta <wcnt+1                ; 256 words
        st0 #$00
        st1 #$00
        st2 #$7f                   ; MAWR = $7f00
        st0 #$02
        jsr copy_words

        ; ---- #16: the raster table (config byte 9).  Copy 16 pages from
        ; ROM bank 1 offset $640 to RAM $2800 — the fixed-layout parallel
        ; arrays the irq1 chain indexes (MPR2 still maps bank 1 from the
        ; SAT copy above; $4640 + 4096 < $6000, no window crossing).
        lda $2209
        beq noraster
        lda #$40
        sta <src
        lda #$46
        sta <src+1
        stz <dst
        lda #$28
        sta <dst+1
        ldx #$10                   ; 16 pages x 256 bytes (the image is
tblpage:                           ; 3844 bytes; the tail padding is inert)
        cly
tblbyte:
        lda [src], Y
        sta [dst], Y
        iny
        bne tblbyte
        inc <src+1
        inc <dst+1
        dex
        bne tblpage

        ; The irq1 vector is the RAM cell $2020: patch the jmp there to
        ; the handler the table's flag bit 0 selects (frame-counter tables
        ; need the counter added to every CRAM value — the #15 scene r4).
        lda #$4c
        sta $2020
        lda $2802                  ; pick the handler BEFORE loading its
        and #$01                   ; address bytes — the and result lands
        beq tblplain               ; in A, which sta $2021 stores
        lda #low(irq1_frm)
        ldx #high(irq1_frm)
        bra tblpatch
tblplain:
        lda #low(irq1_plain)
        ldx #high(irq1_plain)
tblpatch:
        sta $2021
        stx $2022

        stz <step                  ; step 0 and frame counter 0 — the same
        stz <frame                 ; BaseRAM cells the scene ROMs use
        lda $2803
        sta <nsteps                ; the wrap compare
        st0 #$06                   ; arm step 0: r_chain[0] = 0x40 + the
        lda r_chain_lo             ; first entry's line.  RCR = 0x40 fires
        sta $0002                  ; at the VDW entry, before the first
        lda r_chain_hi             ; display line (Mednafen vdc.cpp: the
        sta $0003                  ; match check runs after the VDW-entry
noraster:                          ; counter reset; RCR R06 p. H7-6/7)

        ; ---- show it: CR from config (bit 7 = background on, bit 6 =
        ; sprites on; the #16 builders OR bit 2 (RC) in when a table is
        ; present)
        st0 #$05
        lda $2207
        sta $0002
        st2 #$00

        cli                        ; IRQ1 from here on: the only VDC
                                   ; interrupt enable the builders set is
                                   ; RC (CR bit 2, VDC manual CR R05
                                   ; p. H7-6); VC (bit 3) is never set and
                                   ; the HuC6280 timer is off, so the chain
                                   ; below is the sole interrupt source
loop:
        bra loop

;
; copy_words — copy <wcnt words from ROM (bank <src_bank, 16-bit pointer
; <src) to the VDC data port.  The pointer advances across calls: the tile
; regions are concatenated in the ROM, so each copy must continue where the
; last one left off (an earlier page-walk version kept the byte position in
; Y, which each call reset — every region that did not end on a 256-byte
; page was re-read from the page start, the #14 stripes-scene bug).
; Crossing $5fff re-maps MPR2 to the next bank and resets the pointer to
; $4000 (HuDK's remap_data pattern).  Register 2 of the VDC must be
; selected and MAWR set by the caller.  Clobbers A, X, Y.
;
copy_words:
        lda <wcnt
        ora <wcnt+1
        beq copy_done
        cly                        ; Y stays 0: <src> is the whole pointer
copy_word:
        lda <src+1
        cmp #$60
        bne copy_read
        inc <src_bank              ; crossed the 8 KiB window: next bank
        lda <src_bank
        tam2
        lda #$40
        sta <src+1
copy_read:
        lda [src], Y
        sta $0002
        inc <src
        bne copy_second
        inc <src+1
copy_second:
        lda <src+1
        cmp #$60
        bne copy_high
        inc <src_bank
        lda <src_bank
        tam2
        lda #$40
        sta <src+1
copy_high:
        lda [src], Y
        sta $0003
        inc <src
        bne copy_next
        inc <src+1
copy_next:
        lda <wcnt
        bne copy_low
        dec <wcnt+1
copy_low:
        dec <wcnt
        lda <wcnt
        ora <wcnt+1
        bne copy_word
copy_done:
        rts

; BAT word counts by MWR index ((MWR & $70) >> 4): width 32/64/128/128,
; height 32 rows for 0-3, 64 rows for 4-7 (same order as HuDK's
; bat_width_array / bat_height_array).
bat_words_lo:
        .db $00, $00, $00, $00, $00, $00, $00, $00
bat_words_hi:
        .db $04, $08, $10, $10, $08, $10, $20, $20

;
; irq1 — the #16 RCR chain.  The HuC6280's IRQ1 vector (logical
; $fff8/$fff9, hardware manual §2.4.2 (1) p. H8-13) points at the RAM
; cell $2020, which boot patched to a jmp into one of the two handlers
; below.  The VDC raises IRQ1 when the RCR (register 6) matches the line
; counter and CR bit 2 (RC) is set — VDC manual CR R05 p. H7-6, RCR R06
; p. H7-6/7; the match fires 4 master cycles before the visible line
; ends, and the next line's pixels read the colour table when that
; line's display starts 92 master = ~123 CPU cycles later (Mednafen
; vdc.cpp: HPHASE_HDW_FINAL IncRCR -> HPHASE_HDW line-buffer fill), so a
; CRAM write has ~108 CPU cycles of budget from handler entry, a BXR
; write ~80 and a BYR write ~78.  The write paths below stay inside it
; (the worst case is a two-CRAM step, whose second write lands at ~109
; with the 2-cycle op restores — inside the ~123 hard deadline).
;
; The table: 16 parallel arrays at the fixed page-aligned addresses
; above, indexed by the step counter <step>.  Step n's record is
; r_op[n] (bit 0 BXR, bit 1 BYR, bit 2 CR, bit 3 first CRAM word,
; bit 4 second CRAM word), r_chain[n] (the RCR value arming the next
; step, 0x40 + its line), r_bxr[n], r_byr[n], r_cr[n], and r_a1/r_v1,
; r_a2/r_v2 (the CRAM address/value words).  A step writes its fields by
; shifting the opcode through C (bit order = write order above), bumps
; the step, and re-arms RCR for the next; the last wraps to step 0.
;
; No A/X/Y saves: Y holds the chain's shifted opcode copy and the main
; loop is `bra loop`, which touches nothing,
; and the chain is the only interrupt source (see the cli note above),
; so the pushed P is the only state RTI must restore and the chain
; leaves it alone.  The IRQ1 line is level-sensed (hardware manual
; H8-12/13): it stays high until the status read at the end of the chain
; clears RR — the VDC status register auto-clears on read (VDC manual
; SR R00 p. H7-4; the worked irq1 handler in PCEHeroTN "HuC62 Tech
; Notes" pp. 8-13 reads SR the same way), and the chain cannot re-enter
; while it runs: the next match is a full line away, a line is ~455 CPU
; cycles and the chain runs ~150.
;
; The two handlers differ only in the CRAM value writes: irq1_frm adds
; the frame counter <frame> to every value (the per-frame gradient), the
; same 9-bit add the #15 scene r4 handler does.  Boot picks the handler
; from the table's flag bit 0, so a table without the flag pays no
; cycles for the add (r7's two CRAM words a step is the tight case).
;
irq1_plain:
        ldx <step                  ; 3   the step (ZP $30 = BaseRAM[0x30],
        lda r_op, X                ; 4   the scene ROMs' cell — raster-
        lsr A                      ; 2   patch.py reads it).  The opcode
        tay                        ; 2   is shifted through C (bit order =
        bcc irq1p_nobxr            ; 2   write order below) with the
        st0 #$07                   ; 6   shifted op kept in Y: the field
        lda r_bxr_lo, X            ; 4   writes load bytes into A, so a
        sta $0002                  ; 4   taken field restores the shifted
        lda r_bxr_hi, X            ; 4   op from Y before the next bit
        sta $0003                  ; 4   test.  BXR is valid from the next
        tya                        ; 2   scanning line (R07 p. H7-7)
irq1p_nobxr:
        lsr A                      ; 2   bit 1 -> C: BYR.  Write order AR,
        bcc irq1p_nobyr            ; 2   low, high (VDC manual p. H7-25)
        st0 #$08                   ; 6
        lda r_byr_lo, X            ; 4
        sta $0002                  ; 4
        lda r_byr_hi, X            ; 4
        sta $0003                  ; 4   BYR takes effect the line after
        tya                        ; 2   next (R08 p. H7-7: BYR+1)
        lsr A                      ; 2
irq1p_nobyr:
        lsr A                      ; 2   bit 2 -> C: CR
        bcc irq1p_nocr             ; 2
        st0 #$05                   ; 6
        lda r_cr, X                ; 4
        sta $0002                  ; 4
        st2 #$00                   ; 6
        tya                        ; 2
        lsr A                      ; 2
        lsr A                      ; 2
irq1p_nocr:
        lsr A                      ; 2   bit 3 -> C: first CRAM word
        bcc irq1p_nocram1          ; 2
        lda r_a1_lo, X             ; 4
        sta $0402                  ; 4   colour table address
        lda r_a1_hi, X             ; 4
        sta $0403                  ; 4
        lda r_v1_lo, X             ; 4
        sta $0404                  ; 4   colour word low byte
        lda r_v1_hi, X             ; 4
        sta $0405                  ; 4   high byte: the write lands and
        tya                        ; 2   the CTA advances (CRW R01)
        lsr A                      ; 2
        lsr A                      ; 2
        lsr A                      ; 2
irq1p_nocram1:
        lsr A                      ; 2   bit 4 -> C: second CRAM word
        bcc irq1p_nocram2          ; 2
        lda r_a2_lo, X             ; 4
        sta $0402                  ; 4
        lda r_a2_hi, X             ; 4
        sta $0403                  ; 4
        lda r_v2_lo, X             ; 4
        sta $0404                  ; 4
        lda r_v2_hi, X             ; 4
        sta $0405                  ; 4
irq1p_nocram2:
        jmp irq1step               ; 4

; The frame-counter variant: identical except the CRAM value writes add
; the frame counter (clc/adc <frame>, carry into the high byte, 9 bits).
irq1_frm:
        ldx <step                  ; 3
        lda r_op, X                ; 4
        lsr A                      ; 2
        tay                        ; 2   the shifted op, kept in Y (the
        bcc irq1f_nobxr            ; 2   field writes clobber A; a taken
        st0 #$07                   ; 6   field restores it before the
        lda r_bxr_lo, X            ; 4   next bit test)
        sta $0002                  ; 4
        lda r_bxr_hi, X            ; 4
        sta $0003                  ; 4
        tya                        ; 2
irq1f_nobxr:
        lsr A                      ; 2
        bcc irq1f_nobyr            ; 2
        st0 #$08                   ; 6
        lda r_byr_lo, X            ; 4
        sta $0002                  ; 4
        lda r_byr_hi, X            ; 4
        sta $0003                  ; 4
        tya                        ; 2
        lsr A                      ; 2
irq1f_nobyr:
        lsr A                      ; 2
        bcc irq1f_nocr             ; 2
        st0 #$05                   ; 6
        lda r_cr, X                ; 4
        sta $0002                  ; 4
        st2 #$00                   ; 6
        tya                        ; 2
        lsr A                      ; 2
        lsr A                      ; 2
irq1f_nocr:
        lsr A                      ; 2
        bcc irq1f_nocram1          ; 2
        lda r_a1_lo, X             ; 4
        sta $0402                  ; 4
        lda r_a1_hi, X             ; 4
        sta $0403                  ; 4
        lda r_v1_lo, X             ; 4
        clc                        ; 2
        adc <frame                 ; 3
        sta $0404                  ; 4
        lda r_v1_hi, X             ; 4
        adc #$00                   ; 2
        and #$01                   ; 2
        sta $0405                  ; 4
        tya                        ; 2
        lsr A                      ; 2
        lsr A                      ; 2
        lsr A                      ; 2
irq1f_nocram1:
        lsr A                      ; 2
        bcc irq1f_nocram2          ; 2
        lda r_a2_lo, X             ; 4
        sta $0402                  ; 4
        lda r_a2_hi, X             ; 4
        sta $0403                  ; 4
        lda r_v2_lo, X             ; 4
        clc                        ; 2
        adc <frame                 ; 3
        sta $0404                  ; 4
        lda r_v2_hi, X             ; 4
        adc #$00                   ; 2
        and #$01                   ; 2
        sta $0405                  ; 4
irq1f_nocram2:
        jmp irq1step               ; 4

; The shared step tail (both handlers): bump the step (wrapping to 0),
; bump the frame counter at the wrap when the table's flag bit 0 is set,
; and re-arm RCR for the new step.
irq1step:
        inc <step                  ; 5
        lda <step                  ; 3
        cmp <nsteps                ; 3   the table's step count
        bne irq1arm                ; 2
        stz <step                  ; 3   wrap to step 0
        lda $2802                  ; 4   table flags: bit 0 = frame mode —
        and #$01                   ; 2   the counter bumps at the wrap,
        beq irq1arm                ; 2   before step 0's writes of the
        inc <frame                 ; 5   next frame, so step 0 writes
        lda <frame                 ; 3   grad+counter exactly like the
        and #$1f                   ; 2   scene r4 chain's bump at its
        sta <frame                 ; 3   step-0 fire (raster-patch.py
irq1arm:                               ; folds the saved counter back into
        ldx <step                  ; 3   the table, so the bump's place is
        st0 #$06                   ; 6   invisible in the evidence)
        lda r_chain_lo, X          ; 4   RCR = 0x40 + the next entry's
        sta $0002                  ; 4   line (the #15 convention: an
        lda r_chain_hi, X          ; 4   entry for line L fires at the end
        sta $0003                  ; 4   of line L-1 and its writes land
        lda $0000                  ; 4   for line L).  The status read
        rti                        ; 7   clears RR and drops the IRQ1
                                   ;    line (level-sensed, H8-12/13)

