;;
;; PCEStudio — viewer.asm (cards #8, #14, #16)
;;
;; The viewer ROM: loads the 512-entry colour table into the VCE, tiles and
;; the BAT (and for the sprite scenes the SG patterns) into VRAM, the SAT
;; into VRAM $7f00 where the VDC's SATB DMA picks it up every frame, sets
;; the VDC to 256x240 (VDW = $00EF, 240 display lines, H7-10; HDR = $041F,
;; 32 characters = 256 px, H7-9) and shows the picture.  All picture data is
;; read from
;; fixed places in the ROM; the layout is documented in ../docs/ROM_LAYOUT.md
;; (bank 1: config + 512-entry palettes + the SAT + the #16 raster table,
;; banks 2-3: BAT, banks 4+: tiles, concatenated in descriptor order).
;; Bank 0 is this code and never changes — #9 glues picture data into the
;; fixed places, so the browser's .pce is this bank plus data banks.
;;
;; #70: a wide picture (VCE CR DCC != 00, so a 336- or 512-dot window) writes
;; config version 2 and puts its VCE CR + HSR/HDR in the wide-window block
;; at bank 1 offset $1F00.  Boot then writes those registers instead of the
;; 256-dot constants; every other register is the same.  Version 1 pictures
;; are byte-identical to before (#70 left the config and all offsets alone).
;;
;; #16: pictures with a raster table (config byte 9 = 1) run it on the
;; console: an irq1 handler driven by the VDC's RCR line interrupt writes
;; each line's BXR/BYR/CR/colour-table values and re-arms RCR for the next
;; entry, one step per VDW line (the table and the handler are described
;; below and in ../docs/ROM_LAYOUT.md / ../docs/RENDERER.md).
;;
;; #28: a FLICKER build (gen/flicker.asm) reads config byte $3e (0 = off;
;; else the SAT-order rotation in entries per frame) and $3f (the number of
;; rotated copies).  Boot builds the copies in VRAM and runs a VBlank irq1
;; handler that selects one per frame, so sprites past the VDC's 16-strip
;; line limit are a different set each frame (flicker_setup / flicker_irq
;; below; the rule is mirrored by renderer/pce-flicker.js).  The code is
;; assembled only into flicker builds, so the shared bank 0 the browser
;; export and the #68 trace fixtures pin stays byte-identical.
;;
;; The data banks are generated by tools/genviewer.py from the dumps in
;; tests/dumps/ (see the Makefile); this file alone assembles to the 8 KiB
;; code bank.
;;
;; Adapted from HuDK (BlockoS/HuDK, MIT).  The parts taken from it:
;;   - the reset path (include/irq_reset.s _reset: sei/csh/cld, stack,
;;     tam0/tam1)
;;   - the VDC 256x240 register values (include/vdc.s vdc_init_table)
;;   - the VCE dot-clock value and palette write sequence (include/vce.s
;;     vce_init, vce_load_palette — via the VCE ports, own loop)
;;   - the ROM->VRAM copy pattern with bank remapping (include/vdc.s
;;     vdc_load_data + include/map.s map_data/remap_data: read through an
;;     8 KiB MPR window, re-map the window when the pointer crosses it)
;; The loader, the fixed data layout and the BAT word-count table are ours.
;; The licence notice and adaptation record are at the bottom.
;;
;; Build: see ../docs/BUILD.md.
;;

        .code
        .bank 0
        .org $fff6
        .dw irq2                   ; $fff6
        .dw irq1                   ; $fff8 — #16: irq1 = the RAM cell $2020,
                                   ; a jmp into the chain handler patched at
                                   ; boot (hardware manual §2.4.2 (1)
                                   ; p. H8-13: IRQ1's vector is $fff8/$fff9)
        .dw timer                  ; $fffa
        .dw nmi                    ; $fffc
        .dw reset                  ; $fffe

        .code
        .bank 0
        .org $e000

; Zero-page scratch.  Every access needs the < prefix: pceas emits a bare
; $xx as a 16-bit absolute address, which through MPR0=$ff aliases the I/O
; page instead of the zp RAM.
src      = $10          ; ROM window pointer (src+1 = high byte)
src_bank = $12          ; ROM bank mapped into $4000-$5fff (MPR2)
wcnt     = $13          ; word count (wcnt+1 = high byte)
rgns     = $15          ; tile region counter
cfg      = $16          ; config descriptor pointer (cfg+1 = high byte)
dst      = $18          ; raster table copy destination (dst+1 = high byte)
nsteps   = $1e          ; raster table: the step count (the wrap compare)
; #28: flicker builds only (FLICKER defined).  fphase is live after boot: the
; VBlank handler advances it once a frame; fW is the copy's word rotation.
fstep4   = $1a          ; 4*step: the SAT word-array rotation per phase
fphase   = $1b          ; the phase being built, then the phase on screen
fW       = $1c          ; the copy's word rotation (4*step*phase, mod 256)
fW2      = $1d          ; scratch: 2*fW
step     = $30          ; raster table: the current step — BaseRAM[0x30],
                        ; the cell the #15 scene ROMs' chains use and
                        ; tools/raster-patch.py reads from the save state
frame    = $31          ; raster table: the frame counter (BaseRAM[0x31],
                        ; the same contract)

; #69: the next step's write bytes, prepared by the step tail (and at boot
; for step 0) in the idle time AFTER the interrupt's writes.  The handler
; then only loads and stores them — the counter add, and the table index
; arithmetic, are off the interrupt's critical path.  Eight bytes, because
; the two CRAM words' addresses are as expensive to fetch as their values.
na1_lo   = $32          ; first colour table word: the CTA address (9 bits)
na1_hi   = $33
nv1_lo   = $34          ; and the 9-bit colour value, frame counter added
nv1_hi   = $35
na2_lo   = $36          ; second colour table word
na2_hi   = $37
nv2_lo   = $38
nv2_hi   = $39

; #16: the raster table's parallel per-step arrays in RAM.  Bank 1's copy
; at ROM offset $640 lands at $2800 (16 pages, copied below); the layout
; is fixed for every table — docs/ROM_LAYOUT.md.  Each array is its own
; 256-byte page and holds 240 steps, so the chain's lda array,X never
; crosses a page: every write byte costs 4 cycles.
irq1     = $2020        ; the IRQ1 vector's target: holds jmp ($2240)
irqvec   = $2240        ; and $2240/$2241 the handler prestep selects
                        ; (BaseRAM, above the config copy at $2200-$223f)
r_op     = $2804        ; bit 0 BXR, bit 1 BYR, bit 2 CR, bit 3 first
                        ; CRAM word, bit 4 second CRAM word
r_chain_lo = $2900      ; RCR for the next step = 0x40 + its line
r_chain_hi = $29f0
r_bxr_lo = $2ae0        ; the BXR write (10 bits)
r_bxr_hi = $2bd0
r_byr_lo = $2cc0        ; the BYR write (9 bits)
r_byr_hi = $2db0
r_cr     = $2ea0        ; the CR write (8 bits)
r_a1_lo  = $2f90        ; first CRAM word: colour table address (9 bits)
r_a1_hi  = $3080
r_v1_lo  = $3170        ; and value (9 bits)
r_v1_hi  = $3260
r_a2_lo  = $3350        ; second CRAM word
r_a2_hi  = $3440
r_v2_lo  = $3530
r_v2_hi  = $3620

reset:
        sei                        ; no interrupts
        csh                        ; fast CPU clock
        cld
        ldx #$ff
        txs
        lda #$ff
        tam0                       ; I/O at $0000-$1fff
        lda #$f8
        tam1                       ; work RAM at $2000-$3fff

        ; config + palettes live in bank 1, read through MPR2 ($4000-$5fff)
        lda #$01
        tam2

        ; Copy the 64-byte config block to RAM $2200 (just above the stack,
        ; which only ever holds the two-byte jsr return addresses at $21ff).
        ; The region loop must read its descriptors while MPR2 maps the tile
        ; banks, so the config cannot stay in bank 1: read it once into RAM
        ; and be done with it.
        clx
cfgcopy:
        lda $4000, X
        sta $2200, X
        inx
        cpx #$40                   ; 64 bytes
        bne cfgcopy

        ; ---- VCE CR ($0400): the picture's dot clock (#70).  Version 2
        ; means the wide-window block at bank 1 offset $1F00 is present
        ; ($5F00 in this window; MPR2 is still bank 1).  It carries the
        ; picture's VCE CR, then HSR lo/hi and HDR lo/hi (docs/ROM_LAYOUT.md).
        ; Version 1 pictures are the /4 clock: $04 = DCC 11 (H6-3), the
        ; HuDK vce_init value.  D2 is set in both; it is NOT PROVEN whether
        ; it is the 262/263-line select or edge blur (docs/DECISIONS.md
        ; 2026-10-28, card #27), and every ROM keeps it set.
        lda $2200                  ; config version
        cmp #$02
        bne vce_256
        lda $5F00                  ; wide block: the picture's VCE CR
        sta $0400
        bra vce_done
vce_256:
        lda #$04
        sta $0400
vce_done:

        ; ---- palettes: entries 0-511 (16 BG + 16 sprite palettes) from
        ; ROM $4040 (1024 bytes, bank 1).  Exactly 512 writes: the CTA is 9
        ; bits, so entry 511's write wraps it to 0 and another write would
        ; wipe palettes 0-15 again.
        stz $0402                  ; colour table index = 0 (autoincrements
        stz $0403                  ; after every $0405 write)
        lda #$40
        sta <src
        lda #$40
        sta <src+1
        ldx #$04                   ; 4 pages x 256 bytes = 1024 bytes = 512 words
palpage:
        cly
palentry:
        lda [src], Y
        sta $0404
        iny
        lda [src], Y
        sta $0405
        iny
        bne palentry
        inc <src+1                 ; next 256-byte page
        dex
        bne palpage

        ; ---- VDC registers (HuDK vdc_init_table values; BXR/BYR/MWR/CR come
        ; from the config block, copied to RAM at $2200)
        st0 #$05
        st1 #$00
        st2 #$00                   ; CR: everything off until the data is in
        st0 #$06
        st1 #$00
        st2 #$00                   ; RCR
        st0 #$07
        lda $2202                  ; BXR lo (config offset $02)
        sta $0002
        lda $2203                  ; BXR hi, 10 bits
        and #$03
        sta $0003
        st0 #$08
        lda $2204                  ; BYR lo
        sta $0002
        lda $2205                  ; BYR hi, 9 bits
        and #$01
        sta $0003
        st0 #$09
        lda $2206                  ; MWR
        sta $0002
        st2 #$00
        st0 #$0a
        lda $2200                  ; #70: version 2 -> the block's HSR
        cmp #$02
        bne hsr_256
        lda $5F02                  ; HSR lo (HSW)
        sta $0002
        lda $5F03                  ; HSR hi (HDS)
        sta $0003
        bra hsr_done
hsr_256:
        st1 #$02
        st2 #$02                   ; HSR: HDS=2, HSW=2
hsr_done:
        st0 #$0b
        lda $2200
        cmp #$02
        bne hdr_256
        lda $5F04                  ; HDR lo (HDW)
        sta $0002
        lda $5F05                  ; HDR hi (HDE)
        sta $0003
        bra hdr_done
hdr_256:
        st1 #$1f
        st2 #$04                   ; HDR: HDW=31, HDE=4
hdr_done:
        st0 #$0c
        st1 #$02
        st2 #$0f                   ; VPR
        st0 #$0d
        st1 #$ef
        st2 #$00                   ; VDW: 240 display lines
        st0 #$0e
        st1 #$0c
        st2 #$00                   ; VCR
        st0 #$0f
        st1 #$10
        st2 #$00                   ; DCR: bit 4 (DSR) = VRAM-SATB transfer
                                   ; auto-repeat — the VDC re-DMAs the SAT
                                   ; into the SATB at every VBlank (VDC
                                   ; manual, DCR R0F p. H7-11).  The sprite
                                   ; layer itself is CR bit 6 (below), so
                                   ; this is harmless for sprite-free
                                   ; pictures.
        st0 #$13
        st1 #$00
        st2 #$7f                   ; DVSSR: the SAT sits at VRAM $7f00; the
                                   ; 256-word transfer starts at the next
                                   ; VBlank, triggered by this high-byte
                                   ; write (DVSSR R13 p. H7-12)

        ; ---- BAT: words 0..(width*height-1) of VRAM, from bank 2
        lda $2206                  ; MWR -> word count (HuDK vdc.s bat_width/
        and #$70                   ; bat_height_array order: 32/64/128/128
        lsr A                      ; wide, 32 or 64 rows)
        lsr A
        lsr A
        lsr A
        tax
        lda bat_words_lo, X
        sta <wcnt
        lda bat_words_hi, X
        sta <wcnt+1
        lda #$02
        sta <src_bank
        tam2                       ; map the BAT bank into the window
        stz <src
        lda #$40
        sta <src+1
        st0 #$00
        st1 #$00
        st2 #$00                   ; MAWR = 0
        st0 #$02
        jsr copy_words

        ; ---- tiles: one copy region per config descriptor; the data is the
        ; concatenation of the regions, starting at bank 4 offset 0.  The
        ; descriptors come from the RAM copy of the config ($220a): MPR2 is
        ; mapped to the tile banks for the whole loop, so they cannot be read
        ; from bank 1.
        lda $2208                  ; region count
        sta <rgns
        beq tiles_done
        lda #$04
        sta <src_bank
        tam2                       ; map the first tile bank into the window
        stz <src
        lda #$40
        sta <src+1
        lda #$0a
        sta <cfg
        lda #$22
        sta <cfg+1
region_loop:
        st0 #$00                   ; MAWR = descriptor words 0-1 (VRAM dest)
        cly
        lda [cfg], Y
        sta $0002
        iny
        lda [cfg], Y
        sta $0003
        iny
        lda [cfg], Y               ; word count = descriptor words 2-3
        sta <wcnt
        iny
        lda [cfg], Y
        sta <wcnt+1
        lda <cfg                   ; next descriptor
        clc
        adc #$04
        sta <cfg
        bcc cfg_ok
        inc <cfg+1
cfg_ok:
        st0 #$02
        jsr copy_words
        dec <rgns
        bne region_loop
tiles_done:

        ; ---- SAT: 64 entries x 4 words from bank 1 offset $0440 to VRAM
        ; word $7f00 (DVSSR above).  The CPU cannot write the SATB directly;
        ; the SAT lives in VRAM and the DCR bit-4 DMA carries it into the
        ; SATB at the start of every VBlank (VDC manual 2.4.2 SATB p. H7-20,
        ; DVSSR R13 p. H7-12).  Sprites are still off (CR written below), so
        ; the first displayed frame's SATB already holds this SAT.
.ifdef FLICKER
        ; #28: a flicker picture (config byte $3e = step) does not copy the
        ; SAT once.  flicker_setup builds config byte $3f rotated copies and
        ; installs the VBlank handler that selects one per frame; step = 0
        ; (every non-flicker build) falls through to the plain copy below.
        lda $223e
        beq sat_plain
        jsr flicker_setup
        bra sat_done
.endif
sat_plain:
        lda #$01
        sta <src_bank
        tam2                       ; map bank 1 back into the window
        lda #$40
        sta <src
        lda #$44
        sta <src+1
        stz <wcnt
        lda #$01
        sta <wcnt+1                ; 256 words
        st0 #$00
        st1 #$00
        st2 #$7f                   ; MAWR = $7f00
        st0 #$02
        jsr copy_words
sat_done:

        ; ---- #16: the raster table (config byte 9).  Copy 16 pages from
        ; ROM bank 1 offset $640 to RAM $2800 — the fixed-layout parallel
        ; arrays the irq1 chain indexes (MPR2 still maps bank 1 from the
        ; SAT copy above; $4640 + 4096 < $6000, no window crossing).
        lda $2209
        beq noraster
        lda #$40
        sta <src
        lda #$46
        sta <src+1
        stz <dst
        lda #$28
        sta <dst+1
        ldx #$10                   ; 16 pages x 256 bytes (the image is
tblpage:                           ; 3844 bytes; the tail padding is inert)
        cly
tblbyte:
        lda [src], Y
        sta [dst], Y
        iny
        bne tblbyte
        inc <src+1
        inc <dst+1
        dex
        bne tblpage

        ; #69: the irq1 vector is the RAM cell $2020, which holds
        ; `jmp ($2240)` — an indirect jump through the vector cell the step
        ; tail fills with the handler the NEXT step needs.  Selecting the
        ; step's handler per step (not per table) lets a colour-only step
        ; take the straight-line stub below instead of the op-bit walk,
        ; which is what puts its second colour write inside the blank.
        lda #$6c                   ; jmp (abs)
        sta $2020
        lda #$40                   ; $2240 = the vector cell (above the
        sta $2021                  ; config copy at $2200-$223f)
        lda #$22
        sta $2022

        stz <step                  ; step 0 and frame counter 0 — the same
        stz <frame                 ; BaseRAM cells the scene ROMs use
        lda $2803
        sta <nsteps                ; the wrap compare
        jsr prestep                ; step 0's bytes + handler (frame 0)
        st0 #$06                   ; arm step 0: r_chain[0] = 0x40 + the
        lda r_chain_lo             ; first entry's line.  RCR = 0x40 fires
        sta $0002                  ; at the VDW entry, before the first
        lda r_chain_hi             ; display line (Mednafen vdc.cpp: the
        sta $0003                  ; match check runs after the VDW-entry
noraster:                          ; counter reset; RCR R06 p. H7-6/7)

        ; ---- show it: CR from config (bit 7 = background on, bit 6 =
        ; sprites on; the #16 builders OR bit 2 (RC) in when a table is
        ; present)
        st0 #$05
        lda $2207
.ifdef FLICKER
        ldx $223e                  ; #28: with flicker on, OR bit 3 (VC) —
        beq cr_plain               ; the VBlank interrupt the rotation runs
        ora #$08                   ; on.  Raster tables use RC instead, so
cr_plain:                          ; the two are mutually exclusive.
.endif
        sta $0002
        st2 #$00

        cli                        ; IRQ1 from here on: the only VDC
                                   ; interrupt enable the builders set is
                                   ; RC (CR bit 2, VDC manual CR R05
                                   ; p. H7-6); VC (bit 3) is never set and
                                   ; the HuC6280 timer is off, so the chain
                                   ; below is the sole interrupt source
loop:
        bra loop

;
; copy_words — copy <wcnt words from ROM (bank <src_bank, 16-bit pointer
; <src) to the VDC data port.  The pointer advances across calls: the tile
; regions are concatenated in the ROM, so each copy must continue where the
; last one left off (an earlier page-walk version kept the byte position in
; Y, which each call reset — every region that did not end on a 256-byte
; page was re-read from the page start, the #14 stripes-scene bug).
; Crossing $5fff re-maps MPR2 to the next bank and resets the pointer to
; $4000 (HuDK's remap_data pattern).  Register 2 of the VDC must be
; selected and MAWR set by the caller.  Clobbers A, X, Y.
;
copy_words:
        lda <wcnt
        ora <wcnt+1
        beq copy_done
        cly                        ; Y stays 0: <src> is the whole pointer
copy_word:
        lda <src+1
        cmp #$60
        bne copy_read
        inc <src_bank              ; crossed the 8 KiB window: next bank
        lda <src_bank
        tam2
        lda #$40
        sta <src+1
copy_read:
        lda [src], Y
        sta $0002
        inc <src
        bne copy_second
        inc <src+1
copy_second:
        lda <src+1
        cmp #$60
        bne copy_high
        inc <src_bank
        lda <src_bank
        tam2
        lda #$40
        sta <src+1
copy_high:
        lda [src], Y
        sta $0003
        inc <src
        bne copy_next
        inc <src+1
copy_next:
        lda <wcnt
        bne copy_low
        dec <wcnt+1
copy_low:
        dec <wcnt
        lda <wcnt
        ora <wcnt+1
        bne copy_word
copy_done:
        rts

; BAT word counts by MWR index ((MWR & $70) >> 4): width 32/64/128/128,
; height 32 rows for 0-3, 64 rows for 4-7 (same order as HuDK's
; bat_width_array / bat_height_array).
bat_words_lo:
        .db $00, $00, $00, $00, $00, $00, $00, $00
bat_words_hi:
        .db $04, $08, $10, $10, $08, $10, $20, $20

.ifdef FLICKER
;
; flicker_setup — #28: build <phases> rotated copies of the base SAT in VRAM,
; phase p at VRAM word $7f00 - p*$100.  Rotating the SAT ORDER by step*p
; entries is rotating the 256-word SAT array left by (4*step*p) words, so
; each copy is two contiguous ROM segments: base words W..255, then 0..W-1
; (W = 4*step*p mod 256).  copy_words writes both after one MAWR — the VDC's
; address counter carries across the two calls.
;
; The VDC's line search then sees a different first 16 strips every frame:
; entry k of phase p is base entry (k + step*p) mod 64, so with N populated
; entries the kept ones are base (step*p)..(step*p+15) mod N (the 24-sprite
; fixture: 8 of 24 miss the search each frame, and 4 phases x step 6 show
; every sprite 3 frames of 4).
;
; Clobbers A, X, Y, <src>, <src_bank>, <wcnt>.
;
flicker_setup:
        lda #$01
        sta <src_bank
        tam2                       ; MPR2 = bank 1: the SAT at ROM $4440
        lda $223e                  ; step (entries)
        asl A
        asl A                      ; 4*step = the word-array step
        sta <fstep4
        stz <fphase
        stz <fW                    ; phase 0 is the unrotated order
fs_phase:
        st0 #$00                   ; MAWR = $7f00 - phase*$100
        st1 #$00
        lda #$7f
        sec
        sbc <fphase
        sta $0003
        st0 #$02                   ; VDC data port
        ; segment 1: ROM $4440 + 2W, 256-W words
        lda <fW
        asl A                      ; 2W low; carry = W bit 7
        sta <fW2
        lda #$44
        adc #$00                   ; $44 + that carry
        sta <src+1
        lda #$40
        clc
        adc <fW2
        sta <src
        bcc fs_seg1
        inc <src+1
fs_seg1:
        lda #$00
        sec
        sbc <fW
        sta <wcnt
        lda #$01                   ; 256-W: 1 - borrow (W = 0 gives $0100,
        sbc #$00                   ; not zero — phase 0 copies all 256)
        sta <wcnt+1
        jsr copy_words
        ; segment 2: ROM $4440, W words, continuing at the same VRAM address
        lda #$40
        sta <src
        lda #$44
        sta <src+1
        lda <fW
        sta <wcnt
        stz <wcnt+1
        jsr copy_words
        lda <fW                    ; next phase: W += 4*step (mod 256)
        clc
        adc <fstep4
        sta <fW
        inc <fphase
        lda <fphase
        cmp $223f                  ; phases
        bcc fs_phase
        stz <fphase                ; the SATB starts on phase 0 (DVSSR $7f00)
        lda #$4c                   ; $2020 = jmp flicker_irq (replaces the
        sta $2020                  ; raster chain's jmp ($2240); flicker and
        lda #low(flicker_irq)      ; rasters are mutually exclusive)
        sta $2021
        lda #high(flicker_irq)
        sta $2022
        rts

;
; flicker_irq — #28: once per VBlank, name the next phase's SAT copy.
; The VDC's SATB DMA runs as the display leaves VDW (Mednafen vdc.cpp
; services NeedSATDMATest when VPhase != VDW) and this IRQ fires later, at
; the first blanking line's HPHASE_HDW (DoVBIRQTest), so the DVSSR write
; triggers the NEXT VBlank's transfer: frame F+1 shows the copy this handler
; names.  Reading SR clears VD (R00, p. H7-4) and drops the level-sensed
; IRQ1 line.  No registers need saving: the main loop is `bra loop`.
;
flicker_irq:
        inc <fphase
        lda <fphase
        cmp $223f
        bcc fs_irq_ok
        stz <fphase
fs_irq_ok:
        st0 #$13                   ; DVSSR: the SATB DMA source address
        st1 #$00                   ; low byte $00 (256-word aligned)
        lda #$7f
        sec
        sbc <fphase
        sta $0003                  ; high byte: triggers the transfer
        lda $0000                  ; SR read: clears VD, drops IRQ1
        rti
.endif

;
;
; irq1 — the #16 RCR chain.  The HuC6280's IRQ1 vector (logical
; $fff8/$fff9, hardware manual §2.4.2 (1) p. H8-13) points at the RAM
; cell $2020, which boot fills with `jmp ($2240)`: the indirect jump goes
; through the vector cell the step tail fills with the handler the NEXT
; step needs.  The VDC raises IRQ1 when the RCR (register 6) matches the
; line counter and CR bit 2 (RC) is set — VDC manual CR R05 p. H7-6, RCR
; R06 p. H7-6/7.
;
; #69 — the budget and the shape of this code.  The match fires 4 VDC
; clocks before the visible line ends; the next line's pixels read the
; colour table when its display starts 92 VDC clocks later, i.e. ~123
; CPU cycles minus the interrupt sequence.  Counted with the HuC6280's
; own opcode timings (Software Manual S8-17ff — every memory instruction
; costs ONE cycle more than its 6502 number: LDA abs,X and STA abs 5,
; LDA/STA zp 4, ADC zp 4, LSR A 2, branch 2/4, NOP 2), a colour-table
; store that completes by ~100 CPU cycles from handler entry is in the
; blank; Mednafen measured the boundary at ~100 on a fixture whose
; second word paints the line's first pixel.
;
; The old pair of handlers walked the op byte before every field and did
; the frame-counter add per word: irq1_frm's second store completed at
; ~139 cycles and landed 24 px into the line, irq1_plain's at ~119
; (14 px — invisible only because r7's second word paints the right
; half).  The add and the indexing now happen in prestep, after the
; interrupt's writes; a step whose only writes are colour words takes
; one of the straight-line stubs below, whose second store completes at
; ~72 cycles in the stub (~78 from the vector, counting jmp ($2240)'s 6).  The op walker stays for steps that mix a VDC register
; with colour writes: a two-word mixed step cannot fit the blank at any
; stride (it needs ~120 cycles) and no shipped table uses one — see
; docs/RENDERER.md.
;
; The table: 16 parallel arrays at the fixed page-aligned addresses
; above, indexed by the step counter <step>.  Step n's record is
; r_op[n] (bit 0 BXR, bit 1 BYR, bit 2 CR, bit 3 first CRAM word,
; bit 4 second CRAM word), r_chain[n] (the RCR value arming the next
; step, 0x40 + its line), r_bxr[n], r_byr[n], r_cr[n], and r_a1/r_v1,
; r_a2/r_v2 (the CRAM address/value words).  The last step wraps to 0.
;
; No A/X/Y saves: the main loop is `bra loop` and touches nothing, and
; the chain is the only interrupt source (see the cli note above), so
; the pushed P is the only state RTI must restore.  The IRQ1 line is
; level-sensed (hardware manual H8-12/13): it stays high until the
; status read at the end of the chain clears RR — the VDC status
; register auto-clears on read (VDC manual SR R00 p. H7-4; the worked
; irq1 handler in PCEHeroTN "HuC62 Tech Notes" pp. 8-13 reads SR the
; same way), and the chain cannot re-enter while it runs: the next match
; is a full line away (455 CPU cycles) and the chain runs ~200.

;
; prestep — prepare the NEXT step's write bytes and handler, in the idle
; time after the interrupt's writes (also called at boot for step 0).
; The counter add is the same 9-bit add the #15 scene r4 chain does, and
; the 8-bit CTA address copies keep the handler's loads out of the table
; arrays' ,X indexing.  Clobbers A, X, Y.
;
prestep:
        ldx <step                  ; 4
        lda r_a1_lo, X             ; 5   first colour word: CTA address
        sta <na1_lo                ; 4
        lda r_a1_hi, X
        sta <na1_hi
        lda r_a2_lo, X             ; 5   second colour word: CTA address
        sta <na2_lo
        lda r_a2_hi, X
        sta <na2_hi
        lda $2802                  ; 5   table flags: bit 0 = counter mode
        and #$01                   ; 2
        beq prestep_plain          ; 2/4
        lda r_v1_lo, X             ; 5   value = table value + frame, a
        clc                        ; 2   9-bit add: carry into the high
        adc <frame                 ; 4   bit, masked (the VCE keeps bit 0
        sta <nv1_lo                ; 4   of the high byte — VCE WR c4/c5)
        lda r_v1_hi, X             ; 5
        adc #$00                   ; 2
        and #$01                   ; 2
        sta <nv1_hi                ; 4
        lda r_v2_lo, X             ; 5   the second word gets the same
        clc                        ; 2   per-frame add (REVIEW-16 B15)
        adc <frame                 ; 4
        sta <nv2_lo                ; 4
        lda r_v2_hi, X             ; 5
        adc #$00                   ; 2
        and #$01                   ; 2
        sta <nv2_hi                ; 4
        bra prestep_pick           ; 4
prestep_plain:
        lda r_v1_lo, X             ; 5   no counter: the table bytes as they
        sta <nv1_lo                ; 4   are
        lda r_v1_hi, X
        sta <nv1_hi
        lda r_v2_lo, X
        sta <nv2_lo
        lda r_v2_hi, X
        sta <nv2_hi
prestep_pick:
        lda r_op, X                ; 5   colour-only shapes take a stub
        and #$07                   ; 2   (bits 0-2 clear = no VDC register
        bne prestep_gen            ; 2/4 write)
        lda r_op, X                ; 5
        and #$18                   ; 2
        beq prestep_gen            ; 2/4 no colour word either: the walker
        cmp #$08                   ; 2   bit 3 only -> first word at ~22-36
        beq prestep_c1             ; 2/4
        cmp #$10                   ; 2   bit 4 only
        beq prestep_c2             ; 2/4
        lda #low(irq1_c12)         ; 2   both words: the tight case
        ldx #high(irq1_c12)
        bra prestep_vec            ; 4
prestep_c1:
        lda #low(irq1_c1)
        ldx #high(irq1_c1)
        bra prestep_vec
prestep_c2:
        lda #low(irq1_c2)
        ldx #high(irq1_c2)
        bra prestep_vec
prestep_gen:
        lda #low(irq1_gen)
        ldx #high(irq1_gen)
prestep_vec:
        sta irqvec                 ; 5   $2240/$2241: what jmp ($2240) uses
        stx irqvec+1               ; 5
        rts                        ; 7

;
; The colour-only stubs.  Each is four lazy loads and four stores per
; word: 36 cycles a word.  irq1_c12's last store — the one the line's
; colour table reads — completes at ~72 cycles in the stub, ~78 from
; handler entry with jmp ($2240), inside the ~100 the blank gives.
;
irq1_c1:                           ; op bit 3: the first colour word
        lda <na1_lo                ; 4
        sta $0402                  ; 5   CTA low
        lda <na1_hi                ; 4
        sta $0403                  ; 5   CTA high
        lda <nv1_lo                ; 4
        sta $0404                  ; 5   colour word low byte
        lda <nv1_hi                ; 4
        sta $0405                  ; 5   high byte: the write lands and
        jmp irq1step               ; 4   the CTA advances (CRW R01)
irq1_c2:                           ; op bit 4: the second colour word
        lda <na2_lo
        sta $0402
        lda <na2_hi
        sta $0403
        lda <nv2_lo
        sta $0404
        lda <nv2_hi
        sta $0405
        jmp irq1step
irq1_c12:                          ; both: completes at ~72 cycles
        lda <na1_lo
        sta $0402
        lda <na1_hi
        sta $0403
        lda <nv1_lo
        sta $0404
        lda <nv1_hi
        sta $0405
        lda <na2_lo
        sta $0402
        lda <na2_hi
        sta $0403
        lda <nv2_lo
        sta $0404
        lda <nv2_hi
        sta $0405
        jmp irq1step

;
; irq1_gen — the #16 op walker, kept for steps that mix a VDC register
; with colour writes.  The opcode is shifted through C (bit order = write
; order) with the shifted copy kept in Y: a field's loads clobber A, so a
; taken field restores the shifted op with tya.  The colour values come
; from prestep (so there is no counter arithmetic here).  Over the
; blank's budget for two colour words; no shipped table uses one.
;
irq1_gen:
        ldx <step                  ; 4
        lda r_op, X                ; 5
        lsr A                      ; 2
        tay                        ; 2
        bcc gen_nobxr              ; 2/4
        st0 #$07                   ; 6   BXR: valid from the next line
        lda r_bxr_lo, X            ; 5
        sta $0002                  ; 5
        lda r_bxr_hi, X            ; 5
        sta $0003                  ; 5
        tya                        ; 2
gen_nobxr:
        lsr A
        bcc gen_nobyr
        st0 #$08                   ; 6   BYR: takes effect two lines on
        lda r_byr_lo, X
        sta $0002
        lda r_byr_hi, X
        sta $0003
        tya
        lsr A
gen_nobyr:
        lsr A
        bcc gen_nocr
        st0 #$05                   ; 6   CR
        lda r_cr, X
        sta $0002
        st2 #$00                   ; 6
        tya
        lsr A
        lsr A
gen_nocr:
        lsr A
        bcc gen_nocram1
        lda r_a1_lo, X             ; 5   first colour word
        sta $0402
        lda r_a1_hi, X
        sta $0403
        lda <nv1_lo
        sta $0404
        lda <nv1_hi
        sta $0405
        tya
        lsr A
        lsr A
        lsr A
gen_nocram1:
        lsr A
        bcc gen_nocram2
        lda r_a2_lo, X             ; 5   second colour word
        sta $0402
        lda r_a2_hi, X
        sta $0403
        lda <nv2_lo
        sta $0404
        lda <nv2_hi
        sta $0405
gen_nocram2:
        jmp irq1step

;
; The shared step tail: bump the step (wrapping to 0), bump the frame
; counter at the wrap when the table's flag bit 0 is set, prepare the
; next step's bytes and handler, and re-arm RCR for the new step.
;
irq1step:
        inc <step                  ; 6
        lda <step                  ; 4
        cmp <nsteps                ; 4   the table's step count
        bne irq1arm                ; 2/4
        stz <step                  ; 4   wrap to step 0
        lda $2802                  ; 5   table flags: bit 0 = frame mode —
        and #$01                   ; 2   the counter bumps at the wrap,
        beq irq1arm                ; 2/4 before step 0's writes of the
        inc <frame                 ; 6   next frame, so step 0 writes
        lda <frame                 ; 4   grad+counter exactly like the
        and #$1f                   ; 2   scene r4 chain's bump at its
        sta <frame                 ; 4   step-0 fire (raster-patch.py
irq1arm:                               ; folds the saved counter into the
        jsr prestep                ; 6+7 table, so the bump's place is
        ldx <step                  ; 4   invisible in the evidence)
        st0 #$06                   ; 6   RCR = 0x40 + the next entry's
        lda r_chain_lo, X          ; 5   line (the #15 convention: an
        sta $0002                  ; 5   entry for line L fires at the end
        lda r_chain_hi, X          ; 5   of line L-1 and its writes land
        sta $0003                  ; 5   for line L).  The status read
        lda $0000                  ; 5   clears RR and drops the IRQ1
        rti                        ; 7   line (level-sensed, H8-12/13)

irq2:
timer:
nmi:
        rti

