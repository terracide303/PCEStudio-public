#!/usr/bin/env python3
"""genreview16.py — the #68 fixture REVIEW-16 asked for: one raster table that
uses the field combination no shipped table exercises, "frame counter AND two
CRAM words in one step" (REVIEW-16, *The misses*, B15).

The table is a per-line backdrop ramp (CRAM[0x000], the stripes picture's
visible left half) plus a second per-line word into CRAM[0x1F0] (sprite
palette 15 colour 0, never displayed by this background-only picture), with
the frame counter switched on — the viewer's irq1_frm handler adds the
counter to *both* CRAM words, and removing the add from the second word is
exactly REVIEW-16's B15, which no shipped table could reach (vraster4 is the
only counter table and writes one word; vraster7 is the only two-word table
and has no counter).  The second word is off-screen on purpose: the state
check is its witness, and the reason is the measured line-timing edge in
r11_scene()'s docstring.

The scene is named r11: the #15 scene ROM (a real Mednafen capture, the
renderer's diff-0 oracle) and the #16 viewer ROM (genviewer.py vraster11, the
handler under test) both run the same table.  The table's values and the scene
ROM are generated by tools/genroms.py's own machinery (RASTER_SCENES,
gen_raster_asm, raster_json) with r11 added here, so there is one source of
truth for the picture, the base colour table and the per-line values.  Two
edits are applied to the generated asm, each asserted to occur exactly once:
the frame-counter code genroms.py emits for r4's one-word kind, extended to
both words; and the two-word kind's hard-coded second CTA address (0x007,
which raster7 wants) changed to 0x1F0 to match r11's table.  The
exact-once assertions below refuse to run if that generated code moves.

Usage (tools/genroms.py and tools/genviewer.py are not modified — r11 lives
in this file so the #68 work does not touch a file another card is editing):

    python3 -I tools/genreview16.py                write gen/raster11.asm
                                                   and gen/raster11.raster.json
    python3 -I tools/genreview16.py --build        also assemble
                                                   gen/raster11.pce (pceas)
    python3 -I tools/genreview16.py --viewer       also build gen/vraster11
                                                   from tests/dumps/raster11
                                                   (after that scene capture)
    python3 -I tools/genreview16.py --all          both, in that order
"""

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "gen")
sys.path.insert(0, HERE)

import genroms  # noqa: E402  (the #15 scene generator, imported as a module)


def r11_scene():
    """raster7's picture with the frame counter and two CRAM words a step.

    The first word ramps the backdrop (CRAM[0x000], the visible left half).
    The second word ramps CRAM[0x1F0] — sprite palette 15's colour 0, which
    this background-only picture never displays: the saved colour table
    still shows the value the ROM wrote, so tests/check-raster.js holds the
    per-frame add on the second word to the save state, while the frame is
    not exposed to the write's line timing.  That matters here: the measured
    pristine viewer lands the *second* word of a counter table about 2
    pixels into the next line (the irq1_frm handler's two adds cost ~18 CPU
    cycles more than irq1_plain's, past viewer.asm's ~123-cycle deadline), so
    a visibly-written second word would be a 1-pixel frame mismatch on every
    line rather than a table verdict.  The timing measurement and what it
    leaves unproven are written down with #68; this capture is about the
    table, and the state is its witness.
    """
    entries = [{"line": s + 1,
                "cram": [[0x000, genroms.raster_ramp(s)],
                         [0x1F0, 511 - genroms.raster_ramp(s)]]}
               for s in range(232)]
    return dict(
        kind="cram_dual", mwr=0x00, bxr=0, byr=0, cr=0x84, dcr=genroms.DCR,
        bg="stripes", tiles=[(0x040, 2)], entries=entries,
        cram_ov=genroms.RASTER_HUES_CRAM,
        frame_counter=True,
    )


# The generated irq1 for a cram_dual scene writes the two CRAM words without
# the counter.  These are genroms.gen_raster_asm's own lines (r7's asm); the
# patches insert the r4 frame-counter bump and the 9-bit add, once per word.
BUMP_FROM = ("        ldx <$30                ; step\n"
             "        stz $0402               ; CTA = 0x000 (backdrop entry,")
BUMP_TO = ("        ldx <$30                ; step\n"
           "        bne irq1c11             ; step 0 = first step of a frame:\n"
           "        inc <$31                ; bump the counter before the\n"
           "        lda <$31                ; writes, so every value this\n"
           "        and #$1f                ; frame writes carries it (the\n"
           "        sta <$31                ; #15 scene r4 chain's place)\n"
           "irq1c11:\n"
           "        stz $0402               ; CTA = 0x000 (backdrop entry,")

WORD1_FROM = ("        lda r_step_lo, X\n"
              "        sta $0404\n"
              "        lda r_step_hi, X\n"
              "        sta $0405")
WORD1_TO = ("        lda r_step_lo, X\n"
            "        clc\n"
            "        adc <$31                ; value = ramp(s) + frame, a\n"
            "        sta $0404               ; 9-bit add: carry into the high\n"
            "        lda r_step_hi, X        ; bit, masked\n"
            "        adc #$00\n"
            "        and #$01\n"
            "        sta $0405")

WORD2_ADDR_FROM = ("        lda #$07                ; CTA = 0x007 (palette 0 colour 7,\n"
                   "        sta $0402               ; the right half's colour)\n"
                   "        stz $0403")
WORD2_ADDR_TO = ("        lda #$f0                ; CTA = 0x1f0 (sprite palette 15\n"
                 "        sta $0402               ; colour 0 — never displayed by\n"
                 "        lda #$01                ; this background-only picture;\n"
                 "        sta $0403               ; the saved table is the witness)")

WORD2_FROM = ("        lda r_step2_lo, X\n"
              "        sta $0404\n"
              "        lda r_step2_hi, X\n"
              "        sta $0405")
WORD2_TO = ("        lda r_step2_lo, X\n"
            "        clc\n"
            "        adc <$31                ; the second word gets the same\n"
            "        sta $0404               ; per-frame add (REVIEW-16 B15's\n"
            "        lda r_step2_hi, X       ; site)\n"
            "        adc #$00\n"
            "        and #$01\n"
            "        sta $0405")


def replace_once(text, old, new, what):
    n = text.count(old)
    if n != 1:
        raise SystemExit(f"genreview16: {what}: expected exactly 1 "
                         f"occurrence in the generated asm, found {n} — "
                         f"tools/genroms.py's raster code moved, update the "
                         f"patch")
    return text.replace(old, new)


def write_files():
    genroms.RASTER_SCENES["r11"] = r11_scene()
    # r11 reuses the stripes picture (the BAT half at column 128, the
    # transparent/solid tiles) the #43 scenes define; genroms keys that
    # picture on the scene name, so the name joins the set.
    genroms.RASTER_STRIPES.add("r11")
    asm = genroms.gen_raster_asm("r11")
    asm = replace_once(asm, BUMP_FROM, BUMP_TO, "frame-counter bump")
    asm = replace_once(asm, WORD1_FROM, WORD1_TO, "first CRAM word add")
    asm = replace_once(asm, WORD2_ADDR_FROM, WORD2_ADDR_TO,
                       "second CRAM word address")
    asm = replace_once(asm, WORD2_FROM, WORD2_TO, "second CRAM word add")
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "raster11.asm"), "w") as f:
        f.write(asm)
    table = genroms.raster_json("r11")
    assert table["frameCounter"] is True
    assert all(len(e["cram"]) == 2 for e in table["entries"])
    with open(os.path.join(OUT, "raster11.raster.json"), "w") as f:
        import json
        json.dump(table, f, indent=1)
    print(f"wrote gen/raster11.asm and gen/raster11.raster.json "
          f"({len(table['entries'])} steps, frame counter, two CRAM words)")


def pceas(src, dst):
    exe = os.environ.get("PCEAS", "pceas")
    subprocess.run([exe, "-raw", "-o", dst, src], cwd=HERE, check=True)


def build_scene():
    pceas("gen/raster11.asm", "gen/raster11.pce")
    print("wrote gen/raster11.pce")


def build_viewer():
    import genviewer
    genviewer.build("vraster11")
    pceas("gen/vraster11.asm", "gen/vraster11.pce")
    print("wrote gen/vraster11.pce")


def main():
    args = set(sys.argv[1:])
    if args - {"--build", "--viewer", "--all"}:
        print(__doc__.split("Usage")[-1].strip(), file=sys.stderr)
        return 2
    write_files()
    if "--build" in args or "--all" in args:
        build_scene()
    if "--viewer" in args or "--all" in args:
        build_viewer()
    return 0


if __name__ == "__main__":
    sys.exit(main())
