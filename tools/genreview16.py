#!/usr/bin/env python3
"""genreview16.py — the #68 fixture REVIEW-16 asked for: one raster table that
uses the field combination no shipped table exercises, "frame counter AND two
CRAM words in one step" (REVIEW-16, *The misses*, B15).

The table is a per-line backdrop ramp (CRAM[0x000], the stripes picture's
visible left half) plus a second per-line word into CRAM[0x1F0] (sprite
palette 15 colour 0, never displayed by this background-only picture), with
the frame counter switched on — the viewer's irq1_frm handler adds the
counter to *both* CRAM words, and removing the add from the second word is
exactly REVIEW-16's B15, which no shipped table could reach (vraster4 is the
only counter table and writes one word; vraster7 is the only two-word table
and has no counter).  The second word is off-screen on purpose: the state
check is its witness, and the reason is the measured line-timing edge in
r11_scene()'s docstring.

The scene is named r11: the #15 scene ROM (a real Mednafen capture, the
renderer's diff-0 oracle) and the #16 viewer ROM (genviewer.py vraster11, the
handler under test) both run the same table.  The table's values and the scene
ROM are generated by tools/genroms.py's own machinery (RASTER_SCENES,
gen_raster_asm, raster_json) with r11 added here, so there is one source of
truth for the picture, the base colour table and the per-line values.  Two
edits are applied to the generated asm, each asserted to occur exactly once:
the frame-counter code genroms.py emits for r4's one-word kind, extended to
both words; and the two-word kind's hard-coded second CTA address (0x007,
which raster7 wants) changed to 0x1F0 to match r11's table.  The
exact-once assertions below refuse to run if that generated code moves.

#69 adds a second scene, r12: r11's table with the second CRAM word moved to
CRAM[0x000] — the backdrop cell the line's first pixels use — so the write's
line timing is visible in the frame, and with its values capped at 224 so the
*scene* ROM's own (one-pixel-late) high-byte store is a 0-over-0 no-op.  That
is the visible-second-word fixture #68 could not ship; r12_scene()'s docstring
has the measurements.  Both scenes share the machinery here — the scene's op
template from genroms.py's cram_dual kind, with exactly-once patches for the
frame-counter add and the CTA addresses.

#74 adds r13, the MIXED-op fixture REVIEW-30's V1 no-op asked for: 232 steps
that alternate a colour-only CRAM write and a BYR write.  Every shipped
raster table is homogeneous, so viewer.asm's per-step dispatch vector
($2240) always selects the handler the boot call selected and a stale vector
cannot be seen.  On r13 the identical dispatch code makes a wrong handler
write CRAM where BYR belongs (or the reverse), changing both the frame and
the save state — r13_scene() has the table and the exactly-once handler
patch.  The viewer half is genviewer.py's ordinary vraster13 build.

Usage (tools/genroms.py and tools/genviewer.py are not modified — r11/r12/r13
live in this file so the #68/#69/#74 work does not touch a file another card is
editing).  The scene name defaults to r11:

    python3 -I tools/genreview16.py [r11|r12|r13]   write gen/rasterN.asm
                                                    and gen/rasterN.raster.json
    python3 -I tools/genreview16.py r11 --build     also assemble
                                                    gen/raster11.pce (pceas)
    python3 -I tools/genreview16.py r12 --viewer    also build gen/vraster12
                                                    from tests/dumps/raster12
                                                    (after that scene capture)
    python3 -I tools/genreview16.py r12 --all       both, in that order
"""

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "gen")
sys.path.insert(0, HERE)

import genroms  # noqa: E402  (the #15 scene generator, imported as a module)


def r12_scene():
    """The #69 fixture: r11's picture and frame counter, with the second CRAM
    word on a cell the frame SHOWS.

    r11's second word goes to CRAM[0x1F0], which the background-only stripes
    picture never displays, so a write that lands after the line's first
    pixels began cannot be seen in the frame (#68's reason).  r12 puts the
    second word on CRAM[0x000] — the backdrop cell that the line's first
    pixels use — so the write's line timing IS the picture: a write that
    misses the blank leaves the first pixels of every line on the previous
    value.  The first word keeps the right half's colour 7 (CRAM[0x007]),
    which is written earlier and was never in question.

    The second word's values are capped at 224 so that value + counter
    (0-31) never reaches bit 8: its high byte is always 0.  That matters
    because the #15 *scene* ROM's own handler lands the second word's HIGH
    byte about one pixel late (measured; the viewer's handler is the one
    this card fixes), and a 0-over-0 high-byte store is invisible, while the
    scene's low-byte store — the witness here — is in the blank.  The scene
    ROM stays a diff-0 oracle and the viewer's late write shows as a whole
    line's worth of wrong pixels (measured: 6,287 differing bytes with the
    pre-#69 handler, 0 after).
    """
    entries = [{"line": s + 1,
                "cram": [[0x007, genroms.raster_ramp(s)],
                         [0x000,
                          ((511 - genroms.raster_ramp(s)) * 224) // 511]]}
               for s in range(232)]
    return dict(
        kind="cram_dual", mwr=0x00, bxr=0, byr=0, cr=0x84, dcr=genroms.DCR,
        bg="stripes", tiles=[(0x040, 2)], entries=entries,
        cram_ov=genroms.RASTER_HUES_CRAM,
        frame_counter=True,
    )


def r13_scene():
    """The #74 fixture: a table whose steps alternate the two handler SHAPES.

    REVIEW-30's V1 removed prestep's stores to the dispatch vector ($2240/
    $2241) and the screenshot suite still passed: every shipped table has one
    `r_op` byte for every step, so the handler chosen at boot equals the one
    prestep would choose forever.  r13 mixes them — even steps are
    colour-only (op bit 3, CRAM[0x001], a band hue the picture shows), odd
    steps are BYR-only (op bit 1, a vertical shift the bands picture shows) —
    so a stale vector makes the first odd step write CRAM instead of BYR.
    Both the frame and the saved registers then disagree with the table.

    The table rides on genroms.py's byr_table machinery: `r_step_lo/hi` hold
    each step's ONE write value (the CRAM word on even steps, the BYR value on
    odd ones), which is why the scene dict gives even entries a `byr` key as
    well — that key is only the array's source.  r13_json() below is the
    authoritative table and does not carry it.  The generated handler's
    register branch (st0 #$08; the two value stores) is replaced by the
    alternating handler below, asserted to occur exactly once.

    BYR values step by 14 each odd line ((s*7) & 0x1FF), so consecutive odd
    lines differ by a visibly non-zero row shift on the diagonal bands
    picture; the last odd step (231) leaves BYR = 81, which the save state
    must hold.  The last colour step (230) writes CRAM[1] = ramp(230).
    """
    entries = []
    for s in range(232):
        if s % 2 == 0:
            v = genroms.raster_ramp(s)
            entries.append({"line": s + 1, "cram": [[0x001, v]], "byr": v})
        else:
            entries.append({"line": s + 1, "byr": (s * 7) & 0x1FF})
    return dict(
        kind="byr_table", mwr=0x00, bxr=0, byr=0, cr=0x84, dcr=genroms.DCR,
        bg="bands", tiles=[(0x040, 32)], entries=entries,
        cram_ov=genroms.RASTER_HUES_CRAM,
    )


def r13_json():
    """The mixed table's raster.json (the renderer's and capture's authority).

    Even steps carry `cram` at CRAM[0x001]; odd steps carry `byr`.  The scene
    dict's extra `byr` on even steps exists only to feed gen_raster_asm's
    byr_table step arrays and is deliberately absent here.
    """
    entries = []
    for s in range(232):
        e = {"line": s + 1, "rcr": 0x40 + s + 1}
        if s % 2 == 0:
            e["cram"] = [[0x001, genroms.raster_ramp(s)]]
        else:
            e["byr"] = (s * 7) & 0x1FF
        entries.append(e)
    return {
        "note": ("#74 mixed-op raster fixture r13: even steps colour-only "
                 "(CRAM[0x001]), odd steps BYR-only, one step per VDW line "
                 "— every shipped table is homogeneous, this one witnesses "
                 "the viewer's per-step dispatch (REVIEW-30 V1)"),
        "base": {"bxr": 0, "byr": 0, "cr": 0x84, "dcr": genroms.DCR},
        "baseCram": genroms.scene_cram_words("r13"),
        "frameCounter": False,
        "entries": entries,
    }


def r11_scene():
    """raster7's picture with the frame counter and two CRAM words a step.

    The first word ramps the backdrop (CRAM[0x000], the visible left half).
    The second word ramps CRAM[0x1F0] — sprite palette 15's colour 0, which
    this background-only picture never displays: the saved colour table
    still shows the value the ROM wrote, so tests/check-raster.js holds the
    per-frame add on the second word to the save state, while the frame is
    not exposed to the write's line timing.  That matters here: the measured
    pristine viewer lands the *second* word of a counter table about 2
    pixels into the next line (the irq1_frm handler's two adds cost ~18 CPU
    cycles more than irq1_plain's, past viewer.asm's ~123-cycle deadline), so
    a visibly-written second word would be a 1-pixel frame mismatch on every
    line rather than a table verdict.  The timing measurement and what it
    leaves unproven are written down with #68; this capture is about the
    table, and the state is its witness.
    """
    entries = [{"line": s + 1,
                "cram": [[0x000, genroms.raster_ramp(s)],
                         [0x1F0, 511 - genroms.raster_ramp(s)]]}
               for s in range(232)]
    return dict(
        kind="cram_dual", mwr=0x00, bxr=0, byr=0, cr=0x84, dcr=genroms.DCR,
        bg="stripes", tiles=[(0x040, 2)], entries=entries,
        cram_ov=genroms.RASTER_HUES_CRAM,
        frame_counter=True,
    )


# The generated irq1 for a cram_dual scene writes the two CRAM words without
# the counter.  These are genroms.gen_raster_asm's own lines (r7's asm); the
# patches insert the r4 frame-counter bump and the 9-bit add, once per word.
BUMP_FROM = ("        ldx <$30                ; step\n"
             "        stz $0402               ; CTA = 0x000 (backdrop entry,")
BUMP_TO = ("        ldx <$30                ; step\n"
           "        bne irq1c11             ; step 0 = first step of a frame:\n"
           "        inc <$31                ; bump the counter before the\n"
           "        lda <$31                ; writes, so every value this\n"
           "        and #$1f                ; frame writes carries it (the\n"
           "        sta <$31                ; #15 scene r4 chain's place)\n"
           "irq1c11:\n"
           "        stz $0402               ; CTA = 0x000 (backdrop entry,")

WORD1_FROM = ("        lda r_step_lo, X\n"
              "        sta $0404\n"
              "        lda r_step_hi, X\n"
              "        sta $0405")
WORD1_TO = ("        lda r_step_lo, X\n"
            "        clc\n"
            "        adc <$31                ; value = ramp(s) + frame, a\n"
            "        sta $0404               ; 9-bit add: carry into the high\n"
            "        lda r_step_hi, X        ; bit, masked\n"
            "        adc #$00\n"
            "        and #$01\n"
            "        sta $0405")

WORD2_ADDR_FROM = ("        lda #$07                ; CTA = 0x007 (palette 0 colour 7,\n"
                   "        sta $0402               ; the right half's colour)\n"
                   "        stz $0403")
WORD2_ADDR_TO = ("        lda #$f0                ; CTA = 0x1f0 (sprite palette 15\n"
                 "        sta $0402               ; colour 0 — never displayed by\n"
                 "        lda #$01                ; this background-only picture;\n"
                 "        sta $0403               ; the saved table is the witness)")

WORD2_FROM = ("        lda r_step2_lo, X\n"
              "        sta $0404\n"
              "        lda r_step2_hi, X\n"
              "        sta $0405")
WORD2_TO = ("        lda r_step2_lo, X\n"
            "        clc\n"
            "        adc <$31                ; the second word gets the same\n"
            "        sta $0404               ; per-frame add (REVIEW-16 B15's\n"
            "        lda r_step2_hi, X       ; site)\n"
            "        adc #$00\n"
            "        and #$01\n"
            "        sta $0405")


# r12 (#69): the two fields' CTA addresses are swapped — the second word goes
# to CRAM[0x000], the cell the line's first pixels read, and the first to the
# right half's colour 7.  Applied after the add patches; each FROM carries the
# following value-load line so the two heads stay distinct.
R12_ADDR1_FROM = ("        stz $0402               ; CTA = 0x000 (backdrop entry,\n"
                  "        stz $0403               ; the left half's colour)\n"
                  "        lda r_step_lo, X\n")
R12_ADDR1_TO = ("        lda #$07                ; CTA = 0x007 (palette 0 colour 7,\n"
                "        sta $0402               ; the right half's colour)\n"
                "        stz $0403\n"
                "        lda r_step_lo, X\n")
R12_ADDR2_FROM = ("        lda #$07                ; CTA = 0x007 (palette 0 colour 7,\n"
                  "        sta $0402               ; the right half's colour)\n"
                  "        stz $0403\n"
                  "        lda r_step2_lo, X\n")
R12_ADDR2_TO = ("        stz $0402               ; CTA = 0x000 (the backdrop cell the\n"
                "        stz $0403               ; line's first pixels use)\n"
                "        lda r_step2_lo, X\n")

# r13 (#74): the byr_table handler's single register write becomes a per-step
# shape: even step = colour-only write to CRAM[0x001], odd step = BYR.  The
# exact generated lines are genroms.gen_raster_asm's byr_table branch (its
# `else` for the register kinds); the tail after them (the step bump and RCR
# re-arm) is untouched.  Both branches consume the same r_step_lo/hi value.
# The viewer (tools/viewer.asm) dispatches the SAME op shapes to its own
# stubs, which is what the capture witnesses.
R13_HANDLER_FROM = ("        ldx <$30                ; step\n"
                    "        st0 #$08\n"
                    "        lda r_step_lo, X\n"
                    "        sta $0002\n"
                    "        lda r_step_hi, X\n"
                    "        sta $0003\n")
R13_HANDLER_TO = ("        ldx <$30                ; step (#74: the steps alternate\n"
                  "        txa                     ; two shapes, so a stale viewer dispatch\n"
                  "        and #$01                ; vector cannot write the right one)\n"
                  "        bne irq1r13byr\n"
                  "        lda #$01                ; CTA = 0x001 (palette 0 colour 1,\n"
                  "        sta $0402               ; a band hue the picture shows)\n"
                  "        stz $0403\n"
                  "        lda r_step_lo, X\n"
                  "        sta $0404\n"
                  "        lda r_step_hi, X\n"
                  "        sta $0405\n"
                  "        bra irq1r13done\n"
                  "irq1r13byr:\n"
                  "        st0 #$08                ; BYR: the bands picture shifts\n"
                  "        lda r_step_lo, X\n"
                  "        sta $0002\n"
                  "        lda r_step_hi, X\n"
                  "        sta $0003\n"
                  "irq1r13done:\n")


def replace_once(text, old, new, what):
    n = text.count(old)
    if n != 1:
        raise SystemExit(f"genreview16: {what}: expected exactly 1 "
                         f"occurrence in the generated asm, found {n} — "
                         f"tools/genroms.py's raster code moved, update the "
                         f"patch")
    return text.replace(old, new)


SCENES = {"r11": r11_scene, "r12": r12_scene, "r13": r13_scene}


def write_files(scene="r11"):
    """Write gen/<scene>.asm and gen/<scene>.raster.json."""
    genroms.RASTER_SCENES[scene] = SCENES[scene]()
    # the scene reuses a #43 picture: r11/r12 the stripes (a transparent half
    # and a solid colour-7 half), r13 the bands (diagonal solid-colour tiles,
    # which show a BYR shift); genroms keys that picture on the scene name,
    # so the name joins the set.
    if scene == "r13":
        genroms.RASTER_BANDS.add(scene)
    else:
        genroms.RASTER_STRIPES.add(scene)
    asm = genroms.gen_raster_asm(scene)
    if scene == "r13":
        asm = replace_once(asm, R13_HANDLER_FROM, R13_HANDLER_TO,
                           "mixed-op handler (#74)")
        name = raster_name(scene)
        os.makedirs(OUT, exist_ok=True)
        with open(os.path.join(OUT, f"{name}.asm"), "w") as f:
            f.write(asm)
        table = r13_json()
        assert table["frameCounter"] is False
        import json
        with open(os.path.join(OUT, f"{name}.raster.json"), "w") as f:
            json.dump(table, f, indent=1, sort_keys=True)
        print(f"wrote gen/{name}.asm and gen/{name}.raster.json "
              f"({len(table['entries'])} steps, colour-only and BYR alternating)")
        return
    asm = replace_once(asm, BUMP_FROM, BUMP_TO, "frame-counter bump")
    asm = replace_once(asm, WORD1_FROM, WORD1_TO, "first CRAM word add")
    if scene == "r11":
        asm = replace_once(asm, WORD2_ADDR_FROM, WORD2_ADDR_TO,
                           "second CRAM word address")
    elif scene == "r12":
        asm = replace_once(asm, R12_ADDR2_FROM, R12_ADDR2_TO,
                           "second CRAM word address (CRAM[0x000])")
        asm = replace_once(asm, R12_ADDR1_FROM, R12_ADDR1_TO,
                           "first CRAM word address (CRAM[0x007])")
    else:
        raise SystemExit(f"genreview16: unknown scene {scene!r}")
    asm = replace_once(asm, WORD2_FROM, WORD2_TO, "second CRAM word add")
    name = raster_name(scene)
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, f"{name}.asm"), "w") as f:
        f.write(asm)
    table = genroms.raster_json(scene)
    assert table["frameCounter"] is True
    assert all(len(e["cram"]) == 2 for e in table["entries"])
    import json
    with open(os.path.join(OUT, f"{name}.raster.json"), "w") as f:
        json.dump(table, f, indent=1)
    print(f"wrote gen/{name}.asm and gen/{name}.raster.json "
          f"({len(table['entries'])} steps, frame counter, two CRAM words)")


def pceas(src, dst):
    exe = os.environ.get("PCEAS", "pceas")
    subprocess.run([exe, "-raw", "-o", dst, src], cwd=HERE, check=True)


def raster_name(scene):
    """The scene ROM's file stem: scene r11 -> raster11 (the #15 naming)."""
    return "raster" + scene[1:]


def build_scene(scene="r11"):
    name = raster_name(scene)
    pceas(f"gen/{name}.asm", f"gen/{name}.pce")
    print(f"wrote gen/{name}.pce")


def build_viewer(scene="r11"):
    import genviewer
    genviewer.build(f"vraster{scene[1:]}")
    pceas(f"gen/vraster{scene[1:]}.asm", f"gen/vraster{scene[1:]}.pce")
    print(f"wrote gen/vraster{scene[1:]}.pce")


def main():
    argv = sys.argv[1:]
    scene = "r11"
    if argv and not argv[0].startswith("--"):
        scene = argv.pop(0)
        if scene not in SCENES:
            print(f"unknown scene {scene!r} (r11, r12 or r13)", file=sys.stderr)
            return 2
    args = set(argv)
    if args - {"--build", "--viewer", "--all"}:
        print(__doc__.split("Usage")[-1].strip(), file=sys.stderr)
        return 2
    write_files(scene)
    if "--build" in args or "--all" in args:
        build_scene(scene)
    if "--viewer" in args or "--all" in args:
        build_viewer(scene)
    return 0


if __name__ == "__main__":
    sys.exit(main())
