#!/usr/bin/env node
/*
 * tools/ilvm/gen-note-table.js — generate note(midi)'s table (card #215;
 * design: docs/ROM-SOUND.md §7).
 *
 *   node tools/ilvm/gen-note-table.js tools/ilvm/note-table.inc \
 *                                      tools/ilvm/note-table.h
 *
 * Writes the same 512 values in two forms, both committed and both consumed
 * byte for byte at build time:
 *
 *   note-table.inc  PCEAS .dw list, included by tools/ilvm/hutrack_engine.asm
 *                   into the tables bank at $8C00; the console interpreter
 *                   reads it from ROM there (1,024 B of the bank's free
 *                   space).
 *   note-table.h    a C array tools/ilvm/ilvm_sound.c compiles into the HOST
 *                   harness, whose runs have no ROM to read.
 *
 * The values are renderer/pce-il.js's own noteFrequency() — the function the
 * browser's note builtin runs — so the table cannot drift from the model it
 * must match.  build-engine.sh regenerates both files and fails the build if
 * they differ from the committed copies (a browser-side formula change is a
 * re-pin, like the committed ilvm image).
 *
 * Why 512 entries and not the doc's first 128: the browser's formula returns
 * a nonzero F for midi up to 176 and 4095 for every negative midi.  512
 * entries cover every integer midi the formula distinguishes (0 for >= 512,
 * 4095 for every negative), so a clamp to the table's ends reproduces the
 * browser exactly for ANY midi an int register can hold; 128 entries would
 * answer 9 where the browser answers 8 for midi 128.
 */
"use strict";

const fs = require("fs");
const path = require("path");

const il = require("../../renderer/pce-il.js");

const ENTRIES = 512;

function main() {
  const incPath = process.argv[2];
  const hPath = process.argv[3];
  if (!incPath || !hPath) {
    console.error("usage: gen-note-table.js NOTE-TABLE.inc NOTE-TABLE.h");
    process.exit(2);
  }

  const values = [];
  for (let midi = 0; midi < ENTRIES; midi++) values.push(il.noteFrequency(midi));

  /* The formula's own contract, pinned where the table is made: the first
   * entry is midi 0's clamped 4095 and the tail is 0 once the octave
   * arithmetic reaches it — a generator that stopped early or mis-rounded
   * would move these. */
  if (values[0] !== 4095 || values[ENTRIES - 1] !== 0) {
    console.error("note table shape check failed: [0]=" + values[0] +
                  " [" + (ENTRIES - 1) + "]=" + values[ENTRIES - 1]);
    process.exit(1);
  }

  const inc = [
    "; Generated by tools/ilvm/gen-note-table.js from renderer/pce-il.js's",
    "; noteFrequency(); do not edit.  Card #215; design: docs/ROM-SOUND.md.",
    "; 512 words: midi 0..511 -> the PSG's 12-bit F, so a clamp to the ends",
    "; reproduces the browser for every integer midi (4095 below 0, 0 at",
    "; 512 and up)."
  ];
  for (let i = 0; i < values.length; i += 8) {
    inc.push("    .dw " + values.slice(i, i + 8).join(","));
  }
  inc.push("");

  const h = [
    "/* Generated by tools/ilvm/gen-note-table.js from renderer/pce-il.js's",
    " * noteFrequency(); do not edit.  Card #215; design: docs/ROM-SOUND.md.",
    " * 512 words: midi 0..511 -> the PSG's 12-bit F, so a clamp to the ends",
    " * reproduces the browser for every integer midi (4095 below 0, 0 at",
    " * 512 and up). */",
    "#ifndef ILVM_NOTE_TABLE_H",
    "#define ILVM_NOTE_TABLE_H",
    "",
    "#include <stdint.h>",
    "",
    "static const uint16_t NOTE_TABLE[512] = {"
  ];
  for (let i = 0; i < values.length; i += 8) {
    h.push("  " + values.slice(i, i + 8).join(", ") +
           (i + 8 < values.length ? "," : ""));
  }
  h.push("};", "", "#endif /* ILVM_NOTE_TABLE_H */", "");

  fs.writeFileSync(incPath, inc.join("\n"));
  fs.writeFileSync(hPath, h.join("\n"));
  console.log("note table: " + ENTRIES + " entries -> " +
              path.basename(incPath) + ", " + path.basename(hPath));
}

main();
