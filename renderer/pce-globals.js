/*
 * pce-globals.js — the generated `pceglobals.lua` document (#87).
 *
 * ppu.toys' file bar carries a generated `ppuglobals.lua`: one readable file
 * of the register names their panels write. This is the PC Engine
 * counterpart, and only the names — the registers a toy may set, the rest of
 * the console's address space, the pad's buttons and the Lua helpers the
 * runtime installs. It is generated from the same tables the runtime and the
 * REGISTERS panel read (renderer/pce-toyhost.js, pce-panels.js, pce-psg.js)
 * and from renderer/pce-toys.js's PRELUDE, so a range or a name changed there
 * changes this file. The values a panel writes are the other half of the
 * idea, and they live in main.lua's poke block (#79) — this file never
 * writes a register and is never run.
 *
 * The document is read-only and is not saved with the toy: it is derived
 * from the build, so saving it would make a second copy that could drift.
 * docs/STUDIO.md §2.2 records the mapping.
 */
(function (root, factory) {
  "use strict";
  if (typeof module === "object" && module.exports) {
    module.exports = factory(require("./pce-toys.js"),
                             require("./pce-toyhost.js"),
                             require("./pce-panels.js"),
                             require("./pce-psg.js"));
  } else {
    root.PCEStudio = root.PCEStudio || {};
    root.PCEStudio.globals = factory(root.PCEStudio.toys,
                                     root.PCEStudio.toyhost,
                                     root.PCEStudio.panels,
                                     root.PCEStudio.psg);
  }
})(typeof self !== "undefined" ? self : this,
   function (toys, toyhost, panels, psg) {
  "use strict";

  var NAME = "pceglobals.lua";

  /* 1 -> "R01", 0x400 -> "$0400": the manual's own notation. */
  function hex(n, width) {
    var s = (n >>> 0).toString(16).toUpperCase();
    while (s.length < width) s = "0" + s;
    return s;
  }

  /* The names PRELUDE installs, read from the code that installs them:
   * `function name(...)` at the start of a line, the `a, b = math.x` aliases,
   * and `function password.pack(...)`. `local function` is not a global and
   * is skipped, and so is a helper defined inside another function. PRELUDE
   * is one Lua chunk (a string) in pce-toys.js. */
  function helperNames(prelude) {
    var lines = typeof prelude === "string" ? prelude.split("\n") : (prelude || []);
    var out = [];
    for (var i = 0; i < lines.length; i++) {
      var line = String(lines[i]);
      var fn = /^function ([A-Za-z_][\w.]*)\s*\(/.exec(line);
      if (fn) { out.push(fn[1]); continue; }
      var alias = /^([A-Za-z_]\w*(?:\s*,\s*[A-Za-z_]\w*)*)\s*=\s*math\./.exec(line);
      if (alias) {
        var names = alias[1].split(",");
        for (var k = 0; k < names.length; k++) out.push(names[k].trim());
      }
    }
    var seen = {};
    return out.filter(function (n) {
      if (seen[n]) return false;
      seen[n] = true;
      return true;
    });
  }

  function text() {
    var out = [];
    var line = function (s) { out.push(s == null ? "" : s); };
    /* A comment block under one indent, wrapped to the column. */
    var wrapped = function (prefix, body, width) {
      var words = String(body).split(/\s+/).filter(Boolean);
      var cur = prefix;
      var empty = true;
      for (var i = 0; i < words.length; i++) {
        if (!empty && cur.length + 1 + words[i].length > (width || 76)) {
          out.push(cur);
          cur = prefix + words[i];
        } else {
          cur += (empty ? "" : " ") + words[i];
          empty = false;
        }
      }
      out.push(cur);
    };

    line("-- pceglobals.lua · generated by the Studio (card #87). Read-only.");
    line("-- The register and constant names a PC Engine toy may use, in one file.");
    line("--");
    line("-- The shape follows ppu.toys' ppuglobals.lua (MIT, Copyright (c) 2026");
    line("-- Liora Labs): their file bar carries the document their panels write.");
    line("-- This one carries the names, from the tables the runtime and the");
    line("-- REGISTERS panel read, so a range changed there changes this file.");
    line("-- The values the panels write live in main.lua's poke block (#79).");
    line("--");
    line("-- It is not saved with the toy and it is not run: main.lua is the program.");
    line("");

    /* ---- the toy's own registers ------------------------------------- */
    var regs = (toyhost && toyhost.REGISTERS) || [];
    line("-- The toy's registers — reg(name, value), and only these three");
    for (var i = 0; i < regs.length; i++) {
      var r = regs[i];
      line("--   " + (r.name + "     ").slice(0, 5) + "0.." + r.max);
      wrapped("--         ", (r.what || "") + "; " + r.manual);
    }
    line("");
    line("-- CR's named bits, as a byte (HuC6270 H7-5/H7-6)");
    line("--   BB    128  bit 7  background on (the reset default: CR = 128)");
    line("--   SB     64  bit 6  sprites on");
    line("--   IE_CC   1  bit 0  interrupt enable: colour collision (CC)");
    line("--   IE_OC   2  bit 1  interrupt enable: sprite overflow (OC)");
    line("--   IE_RC   4  bit 2  interrupt enable: raster compare, the line interrupt (RC)");
    line("--   IE_VC   8  bit 3  interrupt enable: vertical blanking (VC)");
    line("");

    /* ---- the VDC ------------------------------------------------------ */
    var vdc = (panels && panels.VDC_REGISTERS) || [];
    line("-- The VDC's address space (HuC6270; pce-panels.js's VDC_REGISTERS)");
    for (var v = 0; v < vdc.length; v++) {
      var d = vdc[v];
      line("--   R" + hex(d.number, 2) + "  " +
           (d.name + "         ").slice(0, 9) + (d.title || ""));
    }
    line("");

    /* ---- the VCE ------------------------------------------------------ */
    line("-- The VCE's write registers (HuC6260; docs/MANUALS.md §6)");
    line("--   $0400  CR    control: dot clock DCC (bits 0-1), blur (bit 2), mono (bit 7)");
    line("--   $0402  CTA   colour-table address, 0..511");
    line("--   $0404  CTW   colour-table write (GGRRRBBB; the address advances)");
    line("");

    /* ---- the PSG ------------------------------------------------------ */
    var psgRegs = (psg && psg.REGISTERS) || [];
    line("-- The PSG's ten write registers (HuC6280; pce-psg.js's REGISTERS)");
    for (var p = 0; p < psgRegs.length; p++) {
      var g = psgRegs[p];
      line("--   R" + g.n + "  " + (g.name + "                 ").slice(0, 17) +
           " (" + g.manual + ")");
    }
    line("");

    /* ---- the pad ------------------------------------------------------ */
    var pads = (toyhost && toyhost.PAD_FIELDS) || [];
    line("-- Pad buttons — pad[1..5].<name>, read-only, refreshed before frame()");
    line("--   " + pads.join(" "));
    line("");

    /* ---- the Lua helpers --------------------------------------------- */
    var helpers = helperNames(toys && toys.PRELUDE);
    if (helpers.length) {
      line("-- Lua helpers the runtime installs before the toy (pce-toys.js)");
      wrapped("--   ", helpers.join(" "));
      line("");
    }

    /* ---- limits ------------------------------------------------------- */
    line("-- Limits (HuC6270/H6, docs/MANUALS.md)");
    line("--   32768 VRAM words · 512 CRAM entries (9-bit) · 64 SAT entries (4 words)");
    line("--   16 sprites per line, counted as 16-pixel strips · 224 display lines");
    line("--   one 60 Hz frame is about 119,904 CPU cycles (7.16-7.19 MHz)");

    return out.join("\n") + "\n";
  }

  return {
    NAME: NAME,
    text: text
  };
});
