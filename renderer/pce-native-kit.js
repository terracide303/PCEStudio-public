/*
 * pce-native-kit.js — the "Download native build kit" zip (docs/NATIVE-KIT.md).
 *
 * The kit is a folder the user unzips and builds with one Node script
 * (tools/native-kit/build.js): the game's own files (main.lua, art, songs), the
 * compiler front end that turns them into C, the C runtime, prebuilt sound-engine
 * images, and the pinned toolchain description.  This module only gathers and
 * zips; the compiler is not run here (the studio's Export dialog has already run
 * the same C emitter, pce-cgen.js, to refuse a game the compiler cannot take).
 *
 * The kit carries the compiler's JavaScript (the very files this page runs)
 * instead of one generated game.c because the build may have to emit the C
 * again with a large function split into pieces, and that needs the compiler.
 *
 * Two inputs the caller supplies, so that the page (fetch) and Node (fs) share
 * the code:
 *   base      the parsed renderer/native-kit-base.json: every static file of the
 *             kit as base64, generated by tools/native-kit/make-base.js
 *   compiler  function(urlOrKitPath) -> source text of one compiler file
 *
 * UMD: Node require and the browser global PCEStudio.nativeKit.
 *   COMPILER_FILES   [{ kit, url }]  the compiler files to fetch and where they go
 *   GAME_FILES       the toy files the kit carries
 *   VERSION          kit version (build.js and toolchain.json carry the same)
 *   build(opts)      { zip, entries, name }
 */
(function (root, factory) {
  if (typeof module === "object" && module.exports) {
    module.exports = factory(require("./pce-zip.js"));
  } else {
    root.PCEStudio = root.PCEStudio || {};
    root.PCEStudio.nativeKit = factory(root.PCEStudio.zip);
  }
}(typeof self !== "undefined" ? self : this, function (zip) {
  "use strict";

  const VERSION = 1;

  /* the closure of tools/toyc/emit.js, tools/native-assets.js, tools/native-songs.js */
  const COMPILER_FILES = [
    "pce-il.js", "pce-sprites.js", "pce-bg.js", "pce-vram.js", "pce-toyhost.js",
    "pce-song.js", "pce-psg.js", "pce-sfx.js", "pce-editor.js", "pce-sat.js", "pce-screen.js",
    "pce-cgen.js", "pce-ilbc.js", "pce-validate.js", "pce-seq.js", "pce-wave.js",
    "pce-hutrack.js"
  ].map((n) => ({ kit: "renderer/" + n, url: n })).concat([
    { kit: "vendor/fengari/fengari-node.js", url: "../vendor/fengari/fengari-node.js" },
    { kit: "vendor/fengari/fengari-web.js", url: "../vendor/fengari/fengari-web.js" }
  ]);

  /* the toy files the compiler reads (tools/toyc/emit.js, native-assets.js, native-songs.js) */
  const GAME_FILES = ["main.lua", "tiles.json", "palettes.json", "sprites.json", "song.json", "songs.json"];

  function utf8(text) { return zip.utf8Encode(String(text)); }

  /* base64 to bytes without atob or Buffer: the studio's stub DOM has neither */
  const B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  function b64ToBytes(b64) {
    const clean = String(b64).replace(/[^A-Za-z0-9+/]/g, "");
    const out = new Uint8Array(Math.floor(clean.length * 3 / 4));
    let acc = 0, bits = 0, at = 0;
    for (let i = 0; i < clean.length; i++) {
      acc = (acc << 6) | B64.indexOf(clean.charAt(i));
      bits += 6;
      if (bits >= 8) { bits -= 8; out[at++] = (acc >> bits) & 0xFF; acc &= (1 << bits) - 1; }
    }
    return out;
  }

  function fail(code, message) {
    const e = new Error(message);
    e.code = code;
    return e;
  }

  /* opts: { base, compiler(url), files: [{name, source}], name }
   * Returns { zip: Uint8Array, entries: [paths], name }. */
  function build(opts) {
    const base = opts && opts.base;
    if (!base || !base.files || base.version !== VERSION) {
      throw fail("kit-base", "the kit's static files (native-kit-base.json) are missing or of another kit version");
    }
    const files = (opts.files || []).filter((f) => GAME_FILES.indexOf(f.name) >= 0);
    if (!files.some((f) => f.name === "main.lua")) throw fail("kit-game", "the toy has no main.lua");
    const entries = [];
    const add = (name, bytes) => entries.push({ name: name, bytes: bytes });
    const top = "pcestudio-native-kit/";
    /* the static files, in a fixed order so the zip is reproducible */
    for (const p of Object.keys(base.files).sort()) add(top + p, b64ToBytes(base.files[p]));
    for (const c of COMPILER_FILES) {
      const text = opts.compiler(c.url);
      if (typeof text !== "string" || !text.length) throw fail("kit-compiler", "could not read " + c.url);
      add(top + c.kit, utf8(text));
    }
    for (const f of files) add(top + "game/" + f.name, utf8(f.source));
    add(top + "game/kit.json", utf8(JSON.stringify({ kit: VERSION, name: opts.name || "game" }) + "\n"));
    return { zip: zip.write(entries), entries: entries.map((e) => e.name), name: opts.name || "game" };
  }

  return { VERSION: VERSION, COMPILER_FILES: COMPILER_FILES, GAME_FILES: GAME_FILES, build: build };
}));
