-- The game.  State is ordinary Lua globals (integers); the entity lists are
-- int arrays because the IL gives an array one element type, and every
-- element here is an int (docs/IL.md §5, #118).
--
-- Sprite slots: 0 the player (sprite #0 for the VDC's own collision flag),
-- 1 the sign, 2..5 the rocks.


-- One frame of the runner: the run cycle is six frames, the jump and the fall
-- one each; the idle pair is unused because the world never stops.
function player_pattern()
  if grounded == 0 then
    if vy < 0 then return 7 end
    return 8
  end
  return 1 + (scroll // 6) % 6
end

-- Lose a life; a hit starts a minute of blinking (one second) so one rock
-- cannot take three lives.
function hurt()
  lives = lives - 1
  inv = 60
  sfx(2, 180, 20, 12)
  if lives <= 0 then state = 2 end
end

-- The rocks roll with the ground, so their screen x is their world x
-- minus the scroll.  A rock already passed the player scores one point.
function move_rocks()
  for i = 1, 4 do
    local x = ROCK_X[i] - scroll
    if x > -32 and x < 256 then
      sprite(1 + i, {x = x + 32, y = GROUND + 1 - 32 + 64,
                     pattern = ROCK[1 + (i - 1) % 2],
                     palette = ROCK_PAL[1 + (i - 1) % 2], cgx = 1, cgy = 1, spbg = 1})
      -- the art's boxes, not the 32-px cells: the character is 16 wide and a
      -- rock's painted part 14, so a well-timed jump clears it
      if x + 23 > px + 10 and x + 9 < px + 22 then
        if py > GROUND - 10 and inv == 0 then hurt() end
      end
      if x + 32 < px and passed[i] == 0 then
        passed[i] = 1
        score = score + 1
      end
    else
      sprite(1 + i, {y = 0})
    end
  end
end

function draw_hud()
  local s = timeleft // 60
  if s < 0 then s = 0 end
  if s > 999 then s = 999 end
  vram[HUD_TIME[1]] = DIGIT_CHARS[(s // 100) % 10 + 1] | (DIGIT_PAL[(s // 100) % 10 + 1] << 12)
  vram[HUD_TIME[2]] = DIGIT_CHARS[(s // 10) % 10 + 1] | (DIGIT_PAL[(s // 10) % 10 + 1] << 12)
  vram[HUD_TIME[3]] = DIGIT_CHARS[s % 10 + 1] | (DIGIT_PAL[s % 10 + 1] << 12)
  local k = score % 1000
  vram[HUD_SCORE[1]] = DIGIT_CHARS[(k // 100) % 10 + 1] | (DIGIT_PAL[(k // 100) % 10 + 1] << 12)
  vram[HUD_SCORE[2]] = DIGIT_CHARS[(k // 10) % 10 + 1] | (DIGIT_PAL[(k // 10) % 10 + 1] << 12)
  vram[HUD_SCORE[3]] = DIGIT_CHARS[k % 10 + 1] | (DIGIT_PAL[k % 10 + 1] << 12)
end

function reset()
  px = START_X
  py = GROUND
  vy = 0
  grounded = 1
  scroll = 0
  timeleft = 60 * 20
  lives = 3
  score = 0
  state = 0
  inv = 60
  passed = {0, 0, 0, 0}
  sky = 0
  music(0)
end

-- The raster split: one table entry at each band's first line, and the
-- register holds to the next entry.  Line 0 puts the bar back at 0 (the
-- register holds last frame's last value until an entry writes it, so
-- without this the bar would scroll), the sky strip has its own counter and
-- the composite below MAIN_LINE runs with the ground.
function bands()
  raster(0, {bxr = 0})
  raster(SKY_LINE, {bxr = sky})
  raster(MAIN_LINE, {bxr = scroll % 256})
end

function init()
  art_boot()
  -- BB (background) | SB (sprites) | CC (the sprite-0 collision enable)
  reg("CR", 0xC3)
  reset()
end

function frame(t, f)
  if state ~= 0 then
    -- the sign reached, or the time and the lives gone: hold the picture and
    -- wait for Run
    if pad[1].run then reset() end
    return
  end

  -- the world runs right at two pixels a frame; the level ends at the sign
  if scroll < LEVEL_LEN then
    scroll = scroll + 2
    sky = (sky + 1) % 256
  end
  bands()
  if timeleft > 0 then timeleft = timeleft - 1 end
  if timeleft <= 0 then state = 2 end

  -- dodge left and right; the player stays on the screen
  if pad[1].left then px = px - 2 end
  if pad[1].right then px = px + 2 end
  if px < 32 then px = 32 end
  if px > 208 then px = 208 end

  -- the jump: one gravity step a frame, the ground at GROUND
  if pad[1].i or pad[1].ii then
    if grounded == 1 then
      vy = -10
      grounded = 0
      sfx(1, 900, 14, 6)
    end
  end
  if grounded == 0 then
    vy = vy + 1
    py = py + vy
    if py >= GROUND then
      py = GROUND
      vy = 0
      grounded = 1
      sfx(3, 300, 10, 4)
    end
  end

  if inv > 0 then inv = inv - 1 end

  move_rocks()

  -- the sign: its screen x follows the scroll like the rocks
  local sx = GOAL_X - scroll
  if sx < 256 and state == 0 then
    sprite(1, {x = sx + 32, y = GROUND + 1 - 32 + 64,
               pattern = SIGNP, palette = SIGN_PAL, cgx = 1, cgy = 1, spbg = 1})
    if sx + 16 < px + 16 then
      state = 1
      score = score + 10
      sfx(4, 1200, 20, 30)
    end
  else
    sprite(1, {y = 0})
  end

  -- the player: sprite #0, blinking while inv runs, 32x64 with the feet at py
  local blink = 0
  if inv > 0 then
    if (inv // 4) % 2 == 0 then blink = 1 end
  end
  if blink == 1 then
    sprite(0, {y = 0})
  else
    local k = player_pattern()
    sprite(0, {x = px + 32, y = py - 63 + 64, pattern = PLY[k],
               palette = PLY_PAL[k], cgx = 1, cgy = 3, spbg = 1})
  end

  draw_hud()
end
