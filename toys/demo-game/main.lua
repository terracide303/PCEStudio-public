function touch_player()
  if inv > 0 then
    inv = inv - 1
  else
    if hit(px, py, ex0, ey0) == 1 then lose_life()
    elseif hit(px, py, ex1, ey1) == 1 then lose_life()
    elseif hit(px, py, ex2, ey2) == 1 then lose_life()
    elseif hit(px, py, ex3, ey3) == 1 then lose_life()
    elseif hit(px, py, ex4, ey4) == 1 then lose_life()
    elseif hit(px, py, ex5, ey5) == 1 then lose_life()
    end
  end
end

-- One digit's pattern for a score digit.  The ten pattern codes sit in VRAM
-- at DIGIT_BASE and are read back with vram[], because a table of ten numbers
-- cannot be read in the IL (il-table-read) and a ten-way if would bury the
-- logic.  VRAM is the one array both runtimes can read.
function digit_pattern(d)
  return vram[DIGIT_BASE + d]
end

-- The HUD.  Score on the right, lives on the left; both are sprites, so the
-- scrolling BAT below cannot carry them.
function draw_hud()
  local d1 = (score // 100) % 10
  local d2 = (score // 10) % 10
  local d3 = score % 10
  sprite(0, {x = 196, y = 68, pattern = digit_pattern(d1), palette = 1})
  sprite(1, {x = 210, y = 68, pattern = digit_pattern(d2), palette = 1})
  sprite(2, {x = 224, y = 68, pattern = digit_pattern(d3), palette = 1})
  if lives >= 1 then
    sprite(3, {x = 8, y = 68, pattern = HEART, palette = 1})
  else
    sprite(3, {y = 0})
  end
  if lives >= 2 then
    sprite(4, {x = 24, y = 68, pattern = HEART, palette = 1})
  else
    sprite(4, {y = 0})
  end
  if lives >= 3 then
    sprite(5, {x = 40, y = 68, pattern = HEART, palette = 1})
  else
    sprite(5, {y = 0})
  end
end

function draw_ship()
  -- a hit flashes the ship off for two frames out of four while inv runs down
  local flash = 0
  if inv > 0 then
    if (inv // 4) % 2 == 0 then flash = 1 end
  end
  if flash == 1 then
    sprite(6, {y = 0})
  else
    sprite(6, {x = px, y = py + 64, pattern = SHIP, palette = 0})
  end
end

