-- main.lua — STARFALL, a small game made only in the studio (card #88).
--
-- WHAT THIS PROVES: a person with the studio's code editor, its SCREEN,
-- SPRITES and PALETTES panels, its toy runtime and its pad can make a game
-- that runs in the browser — and the same file runs through the IL interpreter
-- (the Lua / IL switch in the transport), so it is already inside the path
-- the console back end takes.
--
-- THE GAME: six drones fall through a scrolling starfield.  Move with the
-- D-pad, fire with I.  A hit scores; a collision costs a life.  The top 24
-- lines are a status bar: the RCR line interrupt keeps them still (BYR 0) and
-- a shade darker while the playfield below scrolls (BYR = scroll), which is
-- the raster table's own demonstration.  Score and lives are sprites, because
-- the BAT scrolls under them.
--
-- HOW THE ART GOT HERE: tiles.json / palettes.json / sprites.json in this
-- folder are the picture the SCREEN, SPRITES and PALETTES panels edit.  A toy
-- cannot read those files (there is no asset importer yet — card #117 — see
-- the README's shortfalls), so tools/demo-game-assets.js writes the panels'
-- picture into the block below between the two markers.  Edit the panels, run
--
--     node tools/demo-game-assets.js
--
-- and the block is rewritten; the hand-written game below it is untouched.
-- The generator refuses to run if the markers are gone.
--
-- WHAT IT COULD NOT USE: the card asks for the hardware's collision flags and
-- for toy sound.  A toy cannot read SR (CC/OR) at all (#119), so collisions
-- are arithmetic; and sfx() with no music() is master-muted (#113), so the
-- game's sound writes PSG events that fall silent — the README lists both.
-- The entity lists and the HUD digits are spelled out because the IL refuses
-- to read a table index (#118).
--
-- Everything between the markers is generated: do not edit it by hand.

