-- The game's state lives in globals, one per value instead of an array:
-- the IL's tables are write-only (il-table-read, card #118), so `b[0].x`
-- cannot exist.  That is a shortfall of the toy language this game had to work
-- around; see the README.
--
-- Sprite slots (the SAT):
--   0..2  score digits, hundreds/tens/ones   3..5  lives
--   6     player                             7..12 enemies
--   13..16 bullets
--
-- The pattern numbers (SHIP, ENEMY, BULLET, HEART, DIGIT_*), the starting
-- positions (START_PX, E0X0..) and the two bar colours come from the
-- generated block above, so the picture the panels show and the game's first
-- frame are one source.

function reset_bullet(n)
  if n == 0 then b0l = 0 elseif n == 1 then b1l = 0
  elseif n == 2 then b2l = 0 else b3l = 0 end
end

-- A free bullet leaves from the ship's nose.  No array: four slots, spelled.
function fire()
  if b0l == 0 then
    b0l = 1 b0x = px + 7 b0y = py - 2
  elseif b1l == 0 then
    b1l = 1 b1x = px + 7 b1y = py - 2
  elseif b2l == 0 then
    b2l = 1 b2x = px + 7 b2y = py - 2
  elseif b3l == 0 then
    b3l = 1 b3x = px + 7 b3y = py - 2
  end
end

-- The spawn x for an enemy that left the screen.  A tiny LCG whose product
-- stays inside 32 bits, so Lua and the IL's wrapping int agree by
-- construction: 250 * 37 + 101 < 2^31.
function rnd()
  rng = (rng * 37 + 101) % 251
  return rng
end

-- A 16x16 sprite's box against another: the cell's own coordinates, no
-- hardware status register (a toy cannot read the VDC's CC/OR flags — card
-- #119 — see the README).
function hit(ax, ay, bx, by)
  if abs(ax - bx) < 12 then
    if abs(ay - by) < 12 then return 1 end
  end
  return 0
end

function lose_life()
  lives = lives - 1
  inv = 90
  sfx(2, 220, 20, 16)
  if lives <= 0 then
    lives = 3
    score = 0
  end
end

function init()
  -- the panels' picture: palettes, tiles, the BAT and the sprite patterns
  art_boot()
  -- the SAT as the SPRITES panel shows it: the start state of every slot
  art_sat()

  -- BB (background) and SB (sprites) on.  The toy host starts at BB only
  -- (card #120), so a toy that forgets this draws a SAT nobody can see.
  reg("CR", 0xC0)

  -- The status bar: line 0 freezes the scroll and darkens the backdrop; line
  -- 24 (set every frame) releases the scroll to `scroll` and restores the
  -- backdrop.  The bar is 24 lines, three tile rows.
  raster(0, {byr = 0, cram = {{0, C_BAR}}})

  px = START_PX
  py = START_PY
  lives = 3
  score = 0
  inv = 90
  cooldown = 0
  scroll = 0
  rng = 3

  b0l = 0 b0x = 0 b0y = 0
  b1l = 0 b1x = 0 b1y = 0
  b2l = 0 b2x = 0 b2y = 0
  b3l = 0 b3x = 0 b3y = 0

  ex0 = E0X0 ey0 = E0Y0 es0 = 1
  ex1 = E1X0 ey1 = E1Y0 es1 = 2
  ex2 = E2X0 ey2 = E2Y0 es2 = 1
  ex3 = E3X0 ey3 = E3Y0 es3 = 2
  ex4 = E4X0 ey4 = E4Y0 es4 = 1
  ex5 = E5X0 ey5 = E5Y0 es5 = 1
end

-- Bullets: up four pixels a frame, gone above the bar.
function move_bullets()
  if b0l == 1 then
    b0y = b0y - 4
    if b0y < 26 then b0l = 0 end
  end
  if b1l == 1 then
    b1y = b1y - 4
    if b1y < 26 then b1l = 0 end
  end
  if b2l == 1 then
    b2y = b2y - 4
    if b2y < 26 then b2l = 0 end
  end
  if b3l == 1 then
    b3y = b3y - 4
    if b3y < 26 then b3l = 0 end
  end
end

-- Enemies: down at their own speed, and a hit or a wrap sends them back to
-- the top at a new x.  Six slots, six blocks; there is no loop over the
-- entities because there is no way to index them.
function move_enemies()
  ey0 = ey0 + es0
  if ey0 > 232 then ey0 = 24 ex0 = rnd() % 224 end
  ey1 = ey1 + es1
  if ey1 > 232 then ey1 = 24 ex1 = rnd() % 224 end
  ey2 = ey2 + es2
