function frame(t, f)
  -- the starfield: one pixel a frame, wrapping at the 32-row BAT's 256 lines
  scroll = (scroll + 1) % 256
  reg("BYR", 0)

  -- The RCR split, from the raster table: line 24 releases the scroll and the
  -- playfield's backdrop.  Re-registered every frame because the offset moves.
  raster(24, {byr = scroll, cram = {{0, C_FIELD}}})

  -- pad[1]: the studio's IJKL/NM/OP keys, and the scripted pad in the test
  if pad[1].left then px = px - 2 end
  if pad[1].right then px = px + 2 end
  if pad[1].up then py = py - 2 end
  if pad[1].down then py = py + 2 end
  if px < 0 then px = 0 end
  if px > 240 then px = 240 end
  if py < 34 then py = 34 end
  if py > 200 then py = 200 end

  if cooldown > 0 then cooldown = cooldown - 1 end
  if pad[1].i then
    if cooldown == 0 then
      fire()
      cooldown = 8
      sfx(0, 1100, 14, 4)
    end
  end

  move_bullets()
  move_enemies()
  collide()
  touch_player()

  draw_hud()
  draw_ship()
  draw_bullets()
  draw_enemies()
end
